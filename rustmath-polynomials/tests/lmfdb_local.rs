fn up(c: &[i64]) -> Vec<Integer> { c.iter().map(|&x| Integer::from(x)).collect() }

#[test]
fn cycle_types_match_pari() {
    for &(i, p, _ef, degs, vdisc) in GROUND {
        let ct = cycle_type(&up(&POLYS[i]), p);
        if vdisc == 0 {
            assert_eq!(ct.as_deref(), Some(degs), "cycle_type poly {} p {}", i, p);
        } else {
            assert!(ct.is_none(), "cycle_type None at ramified p={} poly {}", p, i);
        }
    }
}

#[test]
fn ef_decomposition_matches_pari() {
    let (mut committed, mut nonregular) = (0, 0);
    for &(i, p, ef, _degs, vdisc) in GROUND {
        match ramification_type(&up(&POLYS[i]), p) {
            Ok(got) => {
                assert_eq!(got, ef.to_vec(), "ef poly {} p {} (v_p disc={})", i, p, vdisc);
                committed += 1;
            }
            Err(PadicError::NonRegularSegment { .. }) => {
                assert!(vdisc > 0, "NonRegular only at ramified p (poly {} p {})", i, p);
                nonregular += 1;
            }
            Err(e) => panic!("unexpected error poly {} p {}: {:?}", i, p, e),
        }
    }
    // Every committed decomposition matched PARI; every decline was at a ramified
    // prime (asserted above). The declines are ramified primes where the first-order
    // residual polynomial is inseparable (higher-order Montes needed).
    println!("committed {committed} (e,f) decompositions, {nonregular} non-regular declines");
    assert!(committed >= 40, "expected most primes regular, got {committed}");
}

#[test]
fn ef_degrees_sum_to_24() {
    for &(i, p, ..) in GROUND {
        if let Ok(facs) = padic_factor(&up(&POLYS[i]), p) {
            assert_eq!(facs.iter().map(|lf| lf.degree).sum::<usize>(), 24, "sum poly {} p {}", i, p);
        }
    }
}
