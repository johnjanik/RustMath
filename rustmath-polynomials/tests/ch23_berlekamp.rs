// gp: factormod(-x^2-1,5) -> [x + 2, 1; x + 3, 1], pollead((-x^2-1)*Mod(1,5)) -> Mod(4, 5);
//     factormod(5*x^3+x^2+1,5) -> [x + 2, 1; x + 3, 1] (the leading 5 drops out, unit 1);
//     factormod(Pol(7),5) -> matrix(0,2) (unit 2);
//     factormod(3*x+3,3) -> [0, 1] and factormod(x^2+1,4) -> [x, 2] (PARI accepts both;
//     here f ≡ 0 and a composite modulus are errors).
#[test]
fn units_constants_and_errors_match_pari_where_defined() {
    let p5 = Integer::from(5);
    assert_eq!(
        berlekamp::factor(&ints(&[-1, 0, -1]), &p5).unwrap(),
        (
            Integer::from(4),
            vec![(ints(&[2, 1]), 1), (ints(&[3, 1]), 1)]
        )
    );
    assert_eq!(
        berlekamp::factor(&ints(&[1, 0, 1, 5]), &p5).unwrap(),
        (
            Integer::from(1),
            vec![(ints(&[2, 1]), 1), (ints(&[3, 1]), 1)]
        )
    );
    assert_eq!(
        berlekamp::factor(&ints(&[7]), &p5).unwrap(),
        (Integer::from(2), vec![])
    );
    assert!(berlekamp::factor(&ints(&[3, 3]), &Integer::from(3)).is_err());
    assert!(berlekamp::factor(&ints(&[1, 0, 1]), &Integer::from(4)).is_err());
    // A prime above 2^64: x^2 + 1 splits iff p ≡ 1 mod 4. p = 2^89 - 1 ≡ 3 mod 4, so
    // irreducible; gp: factormod(x^2+1, 2^89-1) -> [x^2 + 1, 1].
    let m89 = Integer::from_decimal_str("618970019642690137449562111").unwrap();
    assert_eq!(
        berlekamp::factor(&ints(&[1, 0, 1]), &m89).unwrap(),
        (Integer::from(1), vec![(ints(&[1, 0, 1]), 1)])
    );
}

/// Deterministic 64-bit LCG (Knuth MMIX constants).
struct Lcg(u64);
impl Lcg {
    fn next(&mut self) -> u64 {
        self.0 = self
            .0
            .wrapping_mul(6364136223846793005)
            .wrapping_add(1442695040888963407);
        self.0 >> 33
    }
    fn below(&mut self, m: u64) -> u64 {
        ((self.next() << 31) | self.next()) % m
    }
}

/// Differential test against `fp_factor::factor_with_multiplicity` (distinct-degree plus
/// Cantor-Zassenhaus on i64, an independent implementation that agrees with PARI on 99
/// reference cases): random unit times 1-4 random monic factors of degree 1-5, each raised
/// to a power 1-3 (so p | e occurs for p = 2, 3), padded to degree >= 10 half of the time.
#[test]
fn factor_agrees_with_cantor_zassenhaus() {
    let primes: [u64; 12] = [2, 3, 5, 7, 11, 13, 23, 29, 101, 997, 65537, 2147483647];
    let mut rng = Lcg(0x0023_0008_0002);
    let mut cases = 0;
    for &p in &primes {
        let pi = Integer::from(p);
        for t in 0..20 {
            let mut f: Vec<Integer> = vec![Integer::one()];
            for _ in 0..(1 + rng.below(4)) {
                let d = 1 + rng.below(5);
                let mut g: Vec<Integer> = (0..d).map(|_| Integer::from(rng.below(p))).collect();
                g.push(Integer::one());
                let e = 1 + rng.below(3) as u32;
                f = mul_mod(&f, &pow_mod(&g, e, &pi), &pi);
            }
            while t % 2 == 0 && f.len() < 11 {
                let mut g: Vec<Integer> = (0..1 + rng.below(3))
                    .map(|_| Integer::from(rng.below(p)))
                    .collect();
                g.push(Integer::one());
                f = mul_mod(&f, &g, &pi);
            }
            let unit = Integer::from(1 + rng.below(p - 1));
            let f: Vec<Integer> = f.iter().map(|c| (c * &unit).modulo(&pi)).collect();
            let fi: Vec<i64> = f.iter().map(|c| i64::try_from(c).unwrap()).collect();
            let mut expected: Vec<(Vec<Integer>, u32)> =
                fp_factor::factor_with_multiplicity(&fi, p as i64)
                    .into_iter()
                    .map(|(g, e)| (ints(&g), e))
                    .collect();
            expected.sort_by(|a, b| order(&a.0, &b.0));
            check(
                &pi,
                &f,
                &expected,
                &format!("p = {p}, case {t}, f = {fi:?}"),
            );
            cases += 1;
        }
    }
    assert_eq!(cases, 240);
}

// Q matrix and kernel dimension of the old counterexamples (gp: Qm as in the unit tests;
// #matker(Mod(Qm(f,p),p)~ - 1) = 3): x^11+x^7+x^4+x^3+x^2 mod 2 has 3 distinct factors
// (its null space was undercounted by the old elimination, which skipped a row).
#[test]
fn q_matrix_is_public_and_matches_pari() {
    // gp: Qm(x^2+2, 3) -> [1, 0; 0, 1].
    let q = berlekamp::q_matrix(&ints(&[2, 0, 1]), &Integer::from(3)).unwrap();
    assert_eq!(q, vec![ints(&[1, 0]), ints(&[0, 1])]);
    // gp: factormod(x^11+x^7+x^4+x^3+x^2, 2)
    //   -> [x, 2; x^3 + x^2 + 1, 1; x^6 + x^5 + x^4 + x + 1, 1].
    let (u, f) = berlekamp::factor(
        &ints(&[0, 0, 1, 1, 1, 0, 0, 1, 0, 0, 0, 1]),
        &Integer::from(2),
    )
    .unwrap();
    assert_eq!(u, Integer::from(1));
    assert_eq!(
        f,
        vec![
            (ints(&[0, 1]), 2),
            (ints(&[1, 0, 1, 1]), 1),
            (ints(&[1, 1, 0, 0, 1, 1, 1]), 1),
        ]
    );
}
