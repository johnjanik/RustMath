//! MAGMA Handbook ch. 23 (Univariate Polynomial Rings), §23.8.1 `Factorization` over GF(p)
//! (`Al := "BerlekampSmall"` / `"BerlekampLarge"`), `SquarefreeFactorization`, `QMatrix`;
//! digest `rustmath-lava/docs/Chapter_23_Univariate_Polynomial_Rings.md`. Implementation:
//! `rustmath_polynomials::berlekamp` (Berlekamp 1967; Knuth TAOCP vol. 2 §4.6.2; Cohen GTM 138
//! §3.4; Rabin 1980 for the probabilistic split at p >= 25).
//!
//! Reference values: PARI/GP `factormod`. Every row of `PARI` was produced by
//!
//! ```text
//! gp -q:  F = factormod(Polrev(f), p); vector(#F[,1], i, [lift(Vecrev(F[i,1])), F[i,2]])
//! ```
//!
//! with `f` the little-endian integer coefficient vector of the row (not reduced mod p, so
//! the reduction is tested too). PARI's factors are monic and listed in PARI's own order,
//! which `berlekamp::factor` reproduces (by degree, then by coefficients from the top down).
//! The 152 rows: 37 named cases (cyclotomic and Artin-Schreier polynomials, x^(p^k) - x,
//! repeated factors with multiplicities divisible by p, the inputs on which the old code
//! failed), 64 pseudo-random products of degree >= 10 over 11 primes from 2 to 2^31 - 1,
//! and 47 cases with multiplicities p, p+1, 2p, p^2, p^2+1, 2p^2 and large factor counts
//! (x^64 - 1 mod 257 has 64 linear factors). Primes up to 2^61 - 1.

use rustmath_integers::Integer;
use rustmath_polynomials::factorization::berlekamp_factor_gf;
use rustmath_polynomials::{berlekamp, fp_factor, UnivariatePolynomial};
use std::cmp::Ordering;

fn ints(c: &[i64]) -> Vec<Integer> {
    c.iter().map(|&a| Integer::from(a)).collect()
}

fn trim(mut v: Vec<Integer>) -> Vec<Integer> {
    while v.last().is_some_and(|c| c.is_zero()) {
        v.pop();
    }
    v
}

fn reduce(f: &[Integer], p: &Integer) -> Vec<Integer> {
    trim(f.iter().map(|c| c.modulo(p)).collect())
}

/// Product mod p (schoolbook; test-local, independent of the module under test).
fn mul_mod(a: &[Integer], b: &[Integer], p: &Integer) -> Vec<Integer> {
    if a.is_empty() || b.is_empty() {
        return Vec::new();
    }
    let mut out = vec![Integer::zero(); a.len() + b.len() - 1];
    for (i, x) in a.iter().enumerate() {
        for (j, y) in b.iter().enumerate() {
            out[i + j] = &out[i + j] + &(x * y);
        }
    }
    reduce(&out, p)
}

fn pow_mod(a: &[Integer], e: u32, p: &Integer) -> Vec<Integer> {
    (0..e).fold(vec![Integer::one()], |acc, _| mul_mod(&acc, a, p))
}

/// The factor order of `berlekamp::factor`: degree, then coefficients from the top down.
fn order(a: &[Integer], b: &[Integer]) -> Ordering {
    a.len()
        .cmp(&b.len())
        .then_with(|| a.iter().rev().cmp(b.iter().rev()))
}

/// Checks one input against the expected factorization (monic factors, PARI order).
fn check(p: &Integer, f: &[Integer], expected: &[(Vec<Integer>, u32)], what: &str) {
    let fr = reduce(f, p);
    let u = fr.last().expect("nonzero mod p").clone();
    let (gu, got) = berlekamp::factor(f, p).unwrap_or_else(|e| panic!("{what}: {e}"));
    assert_eq!(gu, u, "{what}: unit");
    assert_eq!(got, expected, "{what}: factors");
    // u · ∏ g^e = f mod p
    let mut prod = vec![u.clone()];
    for (g, e) in &got {
        assert_eq!(g.last(), Some(&Integer::one()), "{what}: monic");
        prod = mul_mod(&prod, &pow_mod(g, *e, p), p);
    }
    assert_eq!(prod, fr, "{what}: product");
    // The UnivariatePolynomial wrapper: the same factors, repeated by multiplicity.
    let flat: Vec<UnivariatePolynomial<Integer>> = got
        .iter()
        .flat_map(|(g, e)| std::iter::repeat_n(UnivariatePolynomial::new(g.clone()), *e as usize))
        .collect();
    let wrapped = berlekamp_factor_gf(&UnivariatePolynomial::new(f.to_vec()), p).unwrap();
    assert_eq!(wrapped, flat, "{what}: berlekamp_factor_gf");
    // Square-free decomposition: s_m = ∏ of the expected factors of multiplicity m.
    let sqf = berlekamp::squarefree_decomposition(f, p).unwrap();
    let mut mults: Vec<u32> = expected.iter().map(|(_, e)| *e).collect();
    mults.sort_unstable();
    mults.dedup();
    let want: Vec<(Vec<Integer>, u32)> = mults
        .iter()
        .map(|&m| {
            let s = expected
                .iter()
                .filter(|(_, e)| *e == m)
                .fold(vec![Integer::one()], |acc, (g, _)| mul_mod(&acc, g, p));
            (s, m)
        })
        .collect();
    assert_eq!(sqf, want, "{what}: squarefree_decomposition");
}

