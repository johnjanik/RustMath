    #[test]
    fn eliminate_recovers_the_twisted_cubic() {
        // Variables: t = 0, x = 1, y = 2, z = 3.
        // I = (x - t, y - t^2, z - t^3); eliminate t.
        // sympy (lex t > x > y > z) gives the t-free elements
        //   x^2 - y, x*y - z, x*z - y^2, y^3 - z^2
        // which generate the twisted cubic ideal (y - x^2, z - x^3).
        let gens = vec![
            var(1) - var(0),
            var(2) - term(1, &[(0, 2)]),
            var(3) - term(1, &[(0, 3)]),
        ];

        let elim = eliminate(gens, &[0]).unwrap();

        assert!(!elim.is_empty(), "elimination ideal must not be empty");
        for p in &elim {
            assert!(
                !p.variables().contains(&0),
                "eliminated variable t leaked into {}",
                p
            );
        }

        // Independently-derived expected ideal (from sympy): (x^2 - y, x*y - z).
        let expected = vec![
            term(1, &[(1, 2)]) - var(2), // x^2 - y
            var(1) * var(2) - var(3),    // x*y - z
        ];
        assert!(
            same_ideal(&elim, &expected),
            "elimination ideal {:?} != twisted cubic ideal",
            elim.iter().map(|p| p.to_string()).collect::<Vec<_>>()
        );

        // And the extra sympy generators really are in it.
        let budget = GroebnerBudget::generous();
        let xz_minus_y2 = var(1) * var(3) - term(1, &[(2, 2)]);
        let y3_minus_z2 = term(1, &[(2, 3)]) - term(1, &[(3, 2)]);
        assert!(
            ideal_membership_field(&xz_minus_y2, &elim, MonomialOrdering::Grevlex, &budget).unwrap()
        );
        assert!(
            ideal_membership_field(&y3_minus_z2, &elim, MonomialOrdering::Grevlex, &budget).unwrap()
        );
    }

