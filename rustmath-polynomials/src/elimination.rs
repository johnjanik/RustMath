    #[test]
    fn univariate_squarefree_part_works() {
        // (x - 1)^2 * (x + 1) = x^3 - x^2 - x + 1  ->  squarefree part (x-1)(x+1) = x^2 - 1
        let f = term(1, &[(0, 3)]) - term(1, &[(0, 2)]) - var(0) + con(1);
        let sf = univariate_squarefree_part(&f).unwrap();
        let expected = term(1, &[(0, 2)]) - con(1);
        assert_eq!(sf, expected, "got {}", sf);

        // Already squarefree: x^2 - 1 stays x^2 - 1.
        let g = term(1, &[(0, 2)]) - con(1);
        assert_eq!(univariate_squarefree_part(&g).unwrap(), g);

        // x^3 -> x
        let h = term(1, &[(0, 3)]);
        assert_eq!(univariate_squarefree_part(&h).unwrap(), var(0));

        // Multivariate is an honest refusal, not a wrong answer.
        let multi = var(0) * var(1);
        assert!(univariate_squarefree_part(&multi).is_err());
    }

