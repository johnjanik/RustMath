    #[test]
    fn krull_dimension_gates() {
        let b = GroebnerBudget::generous();

        // dim k[x,y]/(x) = 1
        assert_eq!(krull_dimension(vec![var(0)], 2, &b).unwrap(), 1);

        // a point (x, y) in the plane has dimension 0
        assert_eq!(krull_dimension(vec![var(0), var(1)], 2, &b).unwrap(), 0);

        // the whole ring k[x,y,z], i.e. the zero ideal, has dimension 3
        assert_eq!(krull_dimension(Vec::<P>::new(), 3, &b).unwrap(), 3);

        // the unit ideal is the empty variety: dimension -1 by our convention
        assert_eq!(krull_dimension(vec![con(1)], 3, &b).unwrap(), -1);

        // the twisted cubic (y - x^2, z - x^3) is a curve: dimension 1
        // x = 0, y = 1, z = 2
        let tc = vec![
            var(1) - term(1, &[(0, 2)]),
            var(2) - term(1, &[(0, 3)]),
        ];
        assert_eq!(krull_dimension(tc, 3, &b).unwrap(), 1);

        // a plane conic in k[x,y]: dimension 1
        let circle = vec![term(1, &[(0, 2)]) + term(1, &[(1, 2)]) - con(1)];
        assert_eq!(krull_dimension(circle, 2, &b).unwrap(), 1);

        // a hypersurface in 3-space has dimension 2
        let surface = vec![term(1, &[(0, 2)]) + term(1, &[(1, 2)]) + term(1, &[(2, 2)]) - con(1)];
        assert_eq!(krull_dimension(surface, 3, &b).unwrap(), 2);

        // zero-dimensional: (x^2 - 1, y^2 - 1) is 4 points
        let four_points = vec![
            term(1, &[(0, 2)]) - con(1),
            term(1, &[(1, 2)]) - con(1),
        ];
        assert_eq!(krull_dimension(four_points, 2, &b).unwrap(), 0);
    }

