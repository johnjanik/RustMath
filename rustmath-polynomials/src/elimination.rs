    #[test]
    fn intersection_of_x_with_itself_is_x_not_x_squared() {
        // This is the test that separates a real intersection from `product`.
        // I = J = (x):  I ∩ J = (x),  but  I · J = (x^2).
        let i = vec![var(0)];
        let j = vec![var(0)];

        let inter = ideal_intersection(i, j).unwrap();

        let x = vec![var(0)];
        let x_squared = vec![term(1, &[(0, 2)])];

        assert!(
            same_ideal(&inter, &x),
            "I ∩ I should be (x), got {:?}",
            inter.iter().map(|p| p.to_string()).collect::<Vec<_>>()
        );
        assert!(
            !same_ideal(&inter, &x_squared),
            "I ∩ I must NOT be the product (x^2) — that would still be the facade"
        );

        // And x itself is in the intersection, while it is not in the product.
        let budget = GroebnerBudget::generous();
        assert!(ideal_membership_field(&var(0), &inter, MonomialOrdering::Grevlex, &budget).unwrap());
        assert!(
            !ideal_membership_field(&var(0), &x_squared, MonomialOrdering::Grevlex, &budget).unwrap()
        );
    }

    #[test]
    fn intersection_of_coprime_principal_ideals_is_the_product() {
        // (x) ∩ (y) = (x*y) — sympy confirms the t-free part is [x*y].
        let inter = ideal_intersection(vec![var(0)], vec![var(1)]).unwrap();
        let expected = vec![var(0) * var(1)];
        assert!(same_ideal(&inter, &expected));
    }

    #[test]
    fn intersection_of_two_maximal_ideals() {
        // sympy: (x, y) ∩ (x, z) = (x, y*z)
        // x = 0, y = 1, z = 2
        let i = vec![var(0), var(1)];
        let j = vec![var(0), var(2)];
        let inter = ideal_intersection(i.clone(), j.clone()).unwrap();

        let expected = vec![var(0), var(1) * var(2)];
        assert!(
            same_ideal(&inter, &expected),
            "expected (x, y*z), got {:?}",
            inter.iter().map(|p| p.to_string()).collect::<Vec<_>>()
        );

        // Sanity: the product (x^2, xz, xy, yz) is strictly smaller — x is not in it.
        let mut product = Vec::new();
        for a in &i {
            for b in &j {
                product.push(a.clone() * b.clone());
            }
        }
        let budget = GroebnerBudget::generous();
        assert!(
            !ideal_membership_field(&var(0), &product, MonomialOrdering::Grevlex, &budget).unwrap(),
            "x should not be in I·J"
        );
        assert!(
            ideal_membership_field(&var(0), &inter, MonomialOrdering::Grevlex, &budget).unwrap(),
            "x must be in I ∩ J"
        );
    }

