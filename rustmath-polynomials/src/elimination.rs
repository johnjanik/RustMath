    /// The degree cap must actually fire — on the *input* and on *produced* elements.
    ///
    /// This test used to be `if let Err(e) = err { assert!(...) }`, which passes
    /// unconditionally whenever the computation succeeds. It asserted nothing. A test that
    /// cannot fail is worse than no test.
    #[test]
    fn degree_budget_trips() {
        // ---- (a) the cap applies to the INPUT generators ----------------------------
        // x^8 - 1 has degree 8. Under max_degree = 3 the budget must refuse it *before*
        // running Buchberger; the old code only ever checked polynomials it produced
        // itself, so a caller could hand in a generator that violated the cap and the
        // limit was silently a lie.
        let gens = vec![term(1, &[(0, 8)]) - con(1), var(1) - var(0)];
        let budget = GroebnerBudget {
            max_degree: 3,
            ..GroebnerBudget::generous()
        };
        let result = eliminate_with_budget(gens.clone(), &[0], &budget);
        assert!(
            matches!(result, Err(_)),
            "a degree-8 input generator must trip max_degree = 3, got Ok"
        );
        let e = result.unwrap_err();
        assert!(
            e.contains("max_degree") && e.contains("input generator"),
            "expected the input-generator degree cap to fire, got: {}",
            e
        );

        // The very same system succeeds once the cap admits the input, which proves the
        // Err above came from the budget and not from some unrelated failure.
        let ok = eliminate_with_budget(gens, &[0], &GroebnerBudget::generous());
        assert!(ok.is_ok(), "x^8 - 1, y - x should eliminate fine: {:?}", ok);

        // ---- (b) the cap applies to elements Buchberger PRODUCES ---------------------
        // (x^3 - y, y^3 - x): both inputs have degree 3, so they pass a max_degree = 3
        // check. Eliminating x forces y^9 - y (sympy: groebner([x**3-y, y**3-x], x, y,
        // order='lex') = [x - y**3, y**9 - y]), which is degree 9 and must trip the cap.
        let deep = vec![
            term(1, &[(0, 3)]) - var(1), // x^3 - y
            term(1, &[(1, 3)]) - var(0), // y^3 - x
        ];
        for g in &deep {
            assert_eq!(g.degree(), Some(3), "the inputs must sit exactly at the cap");
        }

        let result = eliminate_with_budget(deep.clone(), &[0], &budget);
        assert!(
            matches!(result, Err(_)),
            "eliminating x from (x^3 - y, y^3 - x) needs degree 9; max_degree = 3 must trip"
        );
        let e = result.unwrap_err();
        assert!(
            e.contains("max_degree") && e.contains("new basis element"),
            "expected the degree cap to fire on a element Buchberger produced, got: {}",
            e
        );

        // And with a generous budget the same elimination succeeds and really does produce
        // the degree-9 generator, so the cap above fired on a genuine need for degree 9.
        let elim = eliminate_with_budget(deep, &[0], &GroebnerBudget::generous()).unwrap();
        let expected = term(1, &[(1, 9)]) - var(1); // y^9 - y
        assert!(
            same_ideal(&elim, &[expected]),
            "expected the elimination ideal (y^9 - y), got {:?}",
            elim.iter().map(|p| p.to_string()).collect::<Vec<_>>()
        );
    }

    /// The cyclic-n benchmark system: the standard Gröbner basis stress test.
    fn cyclic_system(n: usize) -> Vec<P> {
        let mut gens = Vec::new();
        for d in 1..n {
            let mut sum = P::zero();
            for i in 0..n {
                let mut prod = P::zero();
                prod.add_term(Monomial::new(), q(1));
                for k in 0..d {
                    prod = prod * var((i + k) % n);
                }
                sum = sum + prod;
            }
            gens.push(sum);
        }
        let mut prod = P::zero();
        prod.add_term(Monomial::new(), q(1));
        for i in 0..n {
            prod = prod * var(i);
        }
        gens.push(prod - con(1));
        gens
    }
