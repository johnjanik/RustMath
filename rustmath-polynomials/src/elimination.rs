    #[test]
    fn budget_trips_on_cyclic_6_instead_of_hanging() {
        // Cyclic-6 in an elimination order is a classic Buchberger blow-up: the pair
        // count, the degrees and the term counts all stay modest while the *rational
        // coefficients* explode, so the combinatorial limits never fire and the thing
        // just grinds. This is exactly why the budget carries a wall-clock ceiling.
        //
        // Verified by construction: with no time limit this test hung the whole suite
        // (the 900 s harness cap killed the run). It must now come back as an honest Err.
        let gens = cyclic_system(6);
        let budget = GroebnerBudget {
            max_millis: 4_000,
            ..GroebnerBudget::default()
        };

        let start = std::time::Instant::now();
        let result = eliminate_with_budget(gens, &[0], &budget);
        let elapsed = start.elapsed();

        match result {
            Err(e) => {
                assert!(
                    e.contains("budget exceeded"),
                    "expected a budget error, got: {}",
                    e
                );
                // It must give up promptly, not merely eventually.
                assert!(
                    elapsed.as_secs() < 60,
                    "budget fired but took {:?} to do so",
                    elapsed
                );
            }
            Ok(basis) => panic!(
                "cyclic-6 elimination unexpectedly completed within the budget \
                 ({} elements) — the budget test needs a nastier system",
                basis.len()
            ),
        }
    }

