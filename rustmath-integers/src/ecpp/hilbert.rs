    #[test]
    fn hilbert_roots_give_j() {
        // gp: lift(polrootsmod(polclass(-23), 1000000000933))
        //     = [120712464354, 933014773255, 946269272507]~
        // H_-23 has degree 3, so these three distinct roots are all of its roots mod n.
        let n = BigInt::from(1_000_000_000_933u64);
        let hp = class_polynomial(-23).unwrap();
        let want = big(&[120712464354, 933014773255, 946269272507]);
        for r in &want {
            assert!(eval_mod(&hp, r, &n).is_zero(), "H_-23({r}) mod n");
        }
        let mut rng = super::super::SplitMix64::new(&n);
        for _ in 0..8 {
            let r = super::super::polymod::find_root(&hp, &n, &mut rng)
                .expect("n is prime: no gcd is proper")
                .expect("H_-23 splits mod n");
            assert!(want.contains(&r), "root {r}");
        }
    }
