#[test]
fn legendre_symbol_headline_and_large() {
    // gp: kronecker(a, p) for each pair
    for (a, p, want) in [
        (-1, 7, -1),
        (-3, 7, 1),
        (-1, 3, -1),
        (-1, 5, 1),
        (-2, 7, -1),
        (-5, 11, -1),
        (-6, 7, 1),
        (-14, 7, 0),
        (13, 7, -1),
    ] {
        assert_eq!(i(a).legendre_symbol(&i(p)), Ok(want), "({a}/{p})");
    }
    let m = m127();
    assert_eq!(i(-3).legendre_symbol(&m), Ok(1)); // gp: kronecker(-3, 2^127-1) -> 1
    assert_eq!((-i(2).pow(126)).legendre_symbol(&m), Ok(-1)); // gp: kronecker(-(2^126), 2^127-1)
    assert_eq!(i(-2).legendre_symbol(&m), Ok(-1)); // gp: kronecker(-2, 2^127-1) -> -1
    assert_eq!(i(2).legendre_symbol(&m), Ok(1)); // gp: kronecker(2, 2^127-1) -> 1
                                                 // gp: kronecker(-(10^30+57), 2^127-1) -> -1
    assert_eq!((-(i(10).pow(30) + i(57))).legendre_symbol(&m), Ok(-1));
    // gp: isprime(10^30+57) -> 1; kronecker(-(10^50+151), 10^30+57) -> -1
    assert_eq!(
        (-(i(10).pow(50) + i(151))).legendre_symbol(&(i(10).pow(30) + i(57))),
        Ok(-1)
    );
    // Unchanged contract: the modulus must be an odd prime.
    for p in [2, 15, 1, 0, -7] {
        assert!(i(3).legendre_symbol(&i(p)).is_err(), "p = {p}");
    }
}

