#[test]
fn sqrt_and_legendre_small_primes_brute_force() {
    // Every prime p < 200 and a in -3p..3p against the set of squares {x^2 mod p}.
    for p in small_primes(200) {
        let mut is_square = vec![false; p as usize];
        for x in 0..p {
            is_square[((x * x) % p) as usize] = true;
        }
        for a in -3 * p..=3 * p {
            let res = a.rem_euclid(p);
            let (ai, pi) = (i(a), i(p));
            if is_square[res as usize] {
                assert_root(&ai, &pi);
            } else {
                assert_non_square(&ai, &pi);
            }
            if p > 2 {
                let want = if res == 0 {
                    0
                } else if is_square[res as usize] {
                    1
                } else {
                    -1
                };
                assert_eq!(ai.legendre_symbol(&pi), Ok(want), "({a}/{p})");
            }
        }
    }
}

