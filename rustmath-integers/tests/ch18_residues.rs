#[test]
fn mod_pow_negative_base_and_exponent() {
    let cases: [(i64, i64, i64, i64); 16] = [
        (-2, 3, 7, 6),      // gp: lift(Mod(-2,7)^3) -> 6
        (-3, 5, 7, 2),      // gp: lift(Mod(-3,7)^5) -> 2
        (-1, 1, 7, 6),      // gp: lift(Mod(-1,7)^1) -> 6
        (-1, 2, 7, 1),      // gp: lift(Mod(-1,7)^2) -> 1
        (2, 10, 1000, 24),  // gp: lift(Mod(2,1000)^10) -> 24
        (5, 0, 1, 0),       // gp: lift(Mod(5,1)^0) -> 0
        (0, 0, 7, 1),       // gp: lift(Mod(0,7)^0) -> 1
        (0, 5, 7, 0),       // gp: lift(Mod(0,7)^5) -> 0
        (3, 4, -7, 4),      // gp: lift(Mod(3,-7)^4) -> 4   (Mod(3,-7) == Mod(3,7))
        (-3, 3, -7, 1),     // gp: lift(Mod(-3,-7)^3) -> 1
        (3, 0, -1, 0),      // gp: lift(Mod(3,-1)^0) -> 0
        (2, -1, 7, 4),      // gp: lift(Mod(2,7)^-1) -> 4
        (3, -7, 1000, 123), // gp: lift(Mod(3,1000)^-7) -> 123
        (-5, -3, 12, 7),    // gp: lift(Mod(-5,12)^-3) -> 7
        (-1, -1, 7, 6),     // gp: lift(Mod(-1,7)^-1) -> 6
        (5, -4, 1, 0),      // gp: lift(Mod(5,1)^-4) -> 0
    ];
    for (b, e, m, want) in cases {
        assert_eq!(
            i(b).mod_pow(&i(e), &i(m)),
            Ok(i(want)),
            "mod_pow({b}, {e}, {m})"
        );
        assert_eq!(
            i(b).modpow(&i(e), &i(m)),
            Ok(i(want)),
            "modpow({b}, {e}, {m})"
        );
    }
    // gp: Mod(2,6)^-1 -> error("impossible inverse in Fp_inv: Mod(2, 6).")
    assert_eq!(i(2).mod_pow(&i(-1), &i(6)), Err(MathError::NotInvertible));
    // gp: Mod(0,7)^-1 -> error("impossible inverse in Fp_inv: Mod(7, 7).")
    assert_eq!(i(0).mod_pow(&i(-1), &i(7)), Err(MathError::NotInvertible));
    assert_eq!(i(3).mod_pow(&i(2), &i(0)), Err(MathError::DivisionByZero));
    assert_eq!(i(3).mod_pow(&i(-2), &i(0)), Err(MathError::DivisionByZero));
}

#[test]
fn mod_pow_large_values() {
    let m = m127();
    // gp: lift(Mod(-123456789123456789123, 2^127-1)^(10^30+1))
    assert_eq!(
        z("-123456789123456789123").mod_pow(&(i(10).pow(30) + i(1)), &m),
        Ok(z("61371691356706122463965852923148488378"))
    );
    let e = i(3).pow(60);
    let m40 = i(10).pow(40);
    // gp: lift(Mod(-7, 10^40)^(3^60))
    assert_eq!(
        i(-7).mod_pow(&e, &m40),
        Ok(z("6207534402777984828990956785759508559993"))
    );
    // gp: lift(Mod(-7, 10^40)^(-(3^60)))
    assert_eq!(
        i(-7).mod_pow(&-e, &m40),
        Ok(z("3344956376766121327416229007283993702857"))
    );
    // gp: lift(Mod(-(2^200+3), 2^64)^(2^65+1))
    assert_eq!(
        (-(i(2).pow(200) + i(3))).mod_pow(&(i(2).pow(65) + i(1)), &i(2).pow(64)),
        Ok(z("18446744073709551613"))
    );
}

#[test]
fn mod_pow_fixture() {
    // b, e, m, lift(Mod(b,m)^e) or "E"; 200 rows, |b| < 2^399, |e| < 2^300, m up to 2^276.
    let mut n = 0;
    for r in rows(include_str!("data/modpow_big.csv")) {
        let (b, e, m) = (z(r[0]), z(r[1]), z(r[2]));
        let got = b.mod_pow(&e, &m);
        if r[3] == "E" {
            assert_eq!(got, Err(MathError::NotInvertible), "row {r:?}");
        } else {
            let want = z(r[3]);
            assert_eq!(got, Ok(want.clone()), "row {r:?}");
            assert!(want >= i(0) && want < m.abs());
            // A negative modulus gives the same residue (PARI Mod(b,-m) == Mod(b,m)).
            assert_eq!(b.mod_pow(&e, &-m), Ok(want), "row {r:?} with -m");
        }
        n += 1;
    }
    assert_eq!(n, 200);
}

#[test]
fn mod_pow_small_grid_brute_force() {
    // Independent definition: repeated multiplication with Euclidean remainders; for e < 0
    // the result must invert b^|e| exactly when gcd(b, m) = 1.
    for m in 1i64..=24 {
        for b in -30i64..=30 {
            let mut acc = 1i64.rem_euclid(m);
            for e in 0i64..=12 {
                for mm in [m, -m] {
                    assert_eq!(i(b).mod_pow(&i(e), &i(mm)), Ok(i(acc)), "({b},{e},{mm})");
                }
                if e > 0 {
                    let inv = i(b).mod_pow(&i(-e), &i(m));
                    if m == 1 {
                        assert_eq!(inv, Ok(i(0)));
                    } else if gcd(b, m) == 1 {
                        let inv = inv.unwrap();
                        assert!(inv >= i(0) && inv < i(m));
                        assert_eq!((inv * i(acc)).modulo(&i(m)), i(1), "({b},{},{m})", -e);
                    } else {
                        assert_eq!(inv, Err(MathError::NotInvertible), "({b},{},{m})", -e);
                    }
                }
                acc = (acc * b).rem_euclid(m);
            }
        }
    }
}

fn gcd(a: i64, b: i64) -> i64 {
    let (mut a, mut b) = (a.abs(), b.abs());
    while b != 0 {
        (a, b) = (b, a % b);
    }
    a
}

