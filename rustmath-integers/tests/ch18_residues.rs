//! Residue arithmetic of `Integer` against PARI/GP reference values.
//!
//! MAGMA Handbook ch. 18 (digest `rustmath-lava/docs/Chapter_18_Ring_of_Integers.md`):
//! §18.7 `LegendreSymbol`, `JacobiSymbol`, `KroneckerSymbol`; §18.12.1 `Modexp`, `Modinv`,
//! `Modsqrt`; `Binomial`. Algorithms: H. Cohen, GTM 138, Algorithm 1.4.10 (Kronecker symbol)
//! and Algorithm 1.5.1 (Tonelli-Shanks); Lucas' theorem for `binomial_mod`.
//!
//! Ch. 18 has no worked handbook example for these intrinsics (H18E5 is `DivisorSigma`), so
//! the reference is PARI/GP 2.15.4:
//! - inline values: the `gp` command is in the comment next to each one;
//! - fixtures in `tests/data/*.csv`: generated by `tests/data/gen_csv.gp` (`gp -q < gen_csv.gp`,
//!   `setrand(12345)`; the random streams are those of PARI/GP 2.15.4);
//! - exhaustive small cases are checked against brute force (all squares mod p, repeated
//!   multiplication), which does not depend on the code under test.

use rustmath_core::MathError;
use rustmath_integers::{ArithInt, ArithLLong, Integer};

fn z(s: &str) -> Integer {
    Integer::from_decimal_str(s.trim()).unwrap_or_else(|| panic!("bad integer {s:?}"))
}

fn i(n: i64) -> Integer {
    Integer::from(n)
}

/// 2^127 - 1 (prime; gp `isprime(2^127-1)` = 1).
fn m127() -> Integer {
    i(2).pow(127) - i(1)
}

fn rows(csv: &str) -> impl Iterator<Item = Vec<&str>> {
    csv.lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| l.split(',').collect())
}

fn small_primes(bound: i64) -> Vec<i64> {
    (2..bound)
        .filter(|&n| (2..n).take_while(|d| d * d <= n).all(|d| n % d != 0))
        .collect()
}

fn invalid_argument_message<T: std::fmt::Debug>(r: Result<T, MathError>) -> String {
    match r {
        Err(MathError::InvalidArgument(msg)) => msg,
        other => panic!("expected InvalidArgument, got {other:?}"),
    }
}

