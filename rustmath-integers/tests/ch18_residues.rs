// T5: sqrt_mod_prime / is_quadratic_residue_prime (MAGMA Modsqrt)
// ---------------------------------------------------------------------------------------------

fn assert_root_only(a: &Integer, p: &Integer) {
    let r = a
        .sqrt_mod_prime(p)
        .unwrap_or_else(|e| panic!("sqrt_mod_prime({a}, {p}) = {e:?}"));
    assert!(r >= i(0) && &r < p, "root {r} of {a} not in [0, {p})");
    assert_eq!(
        (r.clone() * r.clone() - a.clone()).modulo(p),
        i(0),
        "{r}^2 != {a} mod {p}"
    );
}

fn assert_root(a: &Integer, p: &Integer) {
    assert_root_only(a, p);
    assert_eq!(a.is_quadratic_residue_prime(p), Ok(true), "{a} mod {p}");
}

fn assert_non_square_only(a: &Integer, p: &Integer) {
    assert_eq!(
        invalid_argument_message(a.sqrt_mod_prime(p)),
        "Not a quadratic residue",
        "sqrt_mod_prime({a}, {p})"
    );
}

fn assert_non_square(a: &Integer, p: &Integer) {
    assert_non_square_only(a, p);
    assert_eq!(a.is_quadratic_residue_prime(p), Ok(false), "{a} mod {p}");
}

#[test]
fn sqrt_mod_prime_negative_inputs() {
    // gp: [issquare(Mod(a,p)), lift(sqrt(Mod(a,p)))]; roots listed as {r, p-r}
    // [-1,7] NONE   [-4,7] NONE
    for (a, p) in [(-1, 7), (-4, 7)] {
        assert_non_square(&i(a), &i(p));
    }
    // [-1,5] {2,3}  [-1,13] {5,8}  [-3,7] {2,5}  [-2,3] {1,2}  [10,13] {6,7}  [-10,13] {4,9}
    // [-1,17] {4,13}  [-1,41] {9,32}  [-8,17] {3,14}  [-2,73] {12,61}  [-3,97] {26,71}
    // [-35,7] 0  [-7,7] 0  [-1,2] 1  [-2,2] 0  [3,2] 1 (kronecker(3,2) = -1, yet 3 = 1^2 mod 2)
    for (a, p) in [
        (-1, 5),
        (-1, 13),
        (-3, 7),
        (-2, 3),
        (10, 13),
        (-10, 13),
        (-1, 17),
        (-1, 41),
        (-8, 17),
        (-2, 73),
        (-3, 97),
        (-35, 7),
        (-7, 7),
        (-1, 2),
        (-2, 2),
        (3, 2),
        (0, 2),
        (1, 2),
    ] {
        assert_root(&i(a), &i(p));
    }
    assert_eq!(i(-35).sqrt_mod_prime(&i(7)), Ok(i(0)));
    assert_eq!(i(-1).sqrt_mod_prime(&i(2)), Ok(i(1)));
    assert_eq!(i(3).sqrt_mod_prime(&i(2)), Ok(i(1)));
    // Composite modulus: both are errors.
    assert!(i(4).sqrt_mod_prime(&i(15)).is_err());
    assert!(i(4).is_quadratic_residue_prime(&i(15)).is_err());
}

#[test]
fn sqrt_mod_prime_large_primes() {
    // P40 = 10000000000041470962696193, p - 1 = 2^40 k (gp: valuation(P40-1,2) -> 40)
    let p40 = z("10000000000041470962696193");
    // gp: lift(sqrt(Mod(-1,P40))) -> {3038218122176766245346970, 6961781877864704717349223}
    assert_root(&i(-1), &p40);
    let r = i(-1).sqrt_mod_prime(&p40).unwrap();
    assert!(r == z("3038218122176766245346970") || r == z("6961781877864704717349223"));
    // gp: -(10^24+7) -> {111201372613485044099590, 9888798627427985918596603}
    let a = -(i(10).pow(24) + i(7));
    let r = a.sqrt_mod_prime(&p40).unwrap();
    assert!(r == z("111201372613485044099590") || r == z("9888798627427985918596603"));
    // gp: issquare(Mod(-(10^24+9), P40)) -> 0
    assert_non_square(&-(i(10).pow(24) + i(9)), &p40);
    // gp: -(123456789012345678901234567890^2) -> {3964419682593043200392761, 6035580317448427762303432}
    let a = -(z("123456789012345678901234567890").pow(2));
    let r = a.sqrt_mod_prime(&p40).unwrap();
    assert!(r == z("3964419682593043200392761") || r == z("6035580317448427762303432"));

    // P5 = 1000000000000000000000000000469 (= 5 mod 8)
    let p5 = z("1000000000000000000000000000469");
    // gp: -1 -> {311780954549239660711255037664, 688219045450760339288744962805}
    let r = i(-1).sqrt_mod_prime(&p5).unwrap();
    assert!(r == z("311780954549239660711255037664") || r == z("688219045450760339288744962805"));
    // gp: -6 -> {87406282730085837229526040648, 912593717269914162770473959821}
    let r = i(-6).sqrt_mod_prime(&p5).unwrap();
    assert!(r == z("87406282730085837229526040648") || r == z("912593717269914162770473959821"));

    // M127 = 2^127 - 1 (= 3 mod 4)
    let m = m127();
    // gp: 2 - 5*M127 -> {2^64, 170141183460469231713240559642174554111}
    let r = (i(2) - i(5) * m.clone()).sqrt_mod_prime(&m).unwrap();
    assert!(r == i(2).pow(64) || r == z("170141183460469231713240559642174554111"));
    assert_non_square(&i(-2), &m); // gp: issquare(Mod(-2, 2^127-1)) -> 0
                                   // gp: -3 -> {78676610129673952743199618487727214612, 91464573330795278988487685228156891115}
    let r = i(-3).sqrt_mod_prime(&m).unwrap();
    assert!(
        r == z("78676610129673952743199618487727214612")
            || r == z("91464573330795278988487685228156891115")
    );
}

