#[test]
fn prime_decomposition_matches_pari() {
    let (mut exact, mut skipped) = (0, 0);
    for &(i, p, ef) in GROUND {
        let f: Vec<Integer> = POLYS[i].iter().map(|&x| Integer::from(x)).collect();
        let d = prime_decomposition(&f, p);
        if d.p_divides_index { skipped += 1; continue; }
        assert_eq!(d.ef(), ef.to_vec(), "ef mismatch poly {} p {}", i, p);
        exact += 1;
    }
    println!("exact (p-not-dividing-index) matches: {}, index-dividing skipped: {}", exact, skipped);
    assert!(exact >= 40, "expected most primes to be index-coprime, got {}", exact);
}
