/// Is `g` (little-endian, monic of degree `e`) **Eisenstein** at `p`:
/// `p ∣ gᵢ` for `0 ≤ i < e` and `p² ∤ g₀`? Such a `g` is irreducible over `ℚ_p` and
/// `K = ℚ_p[π]/(g)` is totally ramified of degree `e` with uniformizer `π`.
pub fn is_eisenstein(g: &[Integer], p: i64) -> bool {
    let e = g.len() - 1;
    if e < 1 || g[e] != Integer::one() {
        return false;
    }
    let pi = Integer::from(p);
    for c in g.iter().take(e) {
        if !(c.clone() % pi.clone()).is_zero() {
            return false;
        }
    }
    let p2 = pi.clone() * pi;
    (g[0].clone() % p2).is_zero() == false && !g[0].is_zero()
}

/// Different exponent `d = v_𝔭(𝔡_{K/ℚ_p}) = v_π(g'(π))` of the totally ramified
/// `K = ℚ_p[π]/(g)` (`g` Eisenstein, `v_π(π)=1`, `v_π(p)=e`). Since `g'(π)` has degree
/// `e−1` (already reduced), `g'(π) = Σᵢ i·gᵢ π^{i−1}` and the terms have distinct
/// `v_π` (distinct residues mod `e`), so
/// `d = min_{i: i·gᵢ≠0} ( e·v_p(i·gᵢ) + (i−1) )`. The discriminant exponent is `d`
/// (residue degree `1`). Tame (`p∤e`) ⇒ `d = e−1`; wild ⇒ larger.
pub fn eisenstein_different_exponent(g: &[Integer], p: i64) -> i64 {
    let e = g.len() - 1;
    let pi = Integer::from(p);
    let mut d: Option<i64> = None;
    for i in 1..=e {
        let coeff = g[i].clone() * Integer::from(i as i64); // i·gᵢ
        if coeff.is_zero() {
            continue;
        }
        let v = e as i64 * coeff.abs().valuation(&pi) as i64 + (i as i64 - 1);
        d = Some(d.map_or(v, |cur| cur.min(v)));
    }
    d.unwrap_or(0)
}

/// An element of a totally ramified extension `K = ℤ_p[π]/(g)`, `g` Eisenstein of
/// degree `e`, truncated to precision `p^N`. `coeffs` (length `e`) are the
/// `c₀ + c₁π + … + c_{e−1}π^{e−1}` coordinates with `cⱼ ∈ ℤ/p^N`. The valuation is
/// `π`-adic: `v_π(π)=1`, `v_π(p)=e`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EisensteinElement {
    pub prime: i64,
    pub precision: u32,
    /// Monic Eisenstein modulus (little-endian).
    pub g: Vec<Integer>,
    pub coeffs: Vec<Integer>,
}

impl EisensteinElement {
    fn e_deg(&self) -> usize {
        self.g.len() - 1
    }

    fn norm(prime: i64, precision: u32, mut coeffs: Vec<Integer>, e: usize) -> Vec<Integer> {
        let m = Integer::from(prime).pow(precision);
        coeffs.resize(e, Integer::zero());
        for c in coeffs.iter_mut() {
            let r = c.clone() % m.clone();
            *c = if r.signum() < 0 { r + m.clone() } else { r };
        }
        coeffs
    }

    pub fn new(prime: i64, precision: u32, g: Vec<Integer>, coeffs: Vec<Integer>) -> Self {
        let e = g.len() - 1;
        let coeffs = Self::norm(prime, precision, coeffs, e);
        EisensteinElement { prime, precision, g, coeffs }
    }

    pub fn zero(prime: i64, precision: u32, g: Vec<Integer>) -> Self {
        let e = g.len() - 1;
        EisensteinElement { prime, precision, g, coeffs: vec![Integer::zero(); e] }
    }

    pub fn one(prime: i64, precision: u32, g: Vec<Integer>) -> Self {
        Self::new(prime, precision, g, vec![Integer::one()])
    }

    /// The uniformizer `π` (a root of `g`).
    pub fn uniformizer(prime: i64, precision: u32, g: Vec<Integer>) -> Self {
        Self::new(prime, precision, g, vec![Integer::zero(), Integer::one()])
    }

    pub fn from_int(prime: i64, precision: u32, g: Vec<Integer>, n: Integer) -> Self {
        Self::new(prime, precision, g, vec![n])
    }

    pub fn is_zero(&self) -> bool {
        self.coeffs.iter().all(|c| c.is_zero())
    }

    pub fn add(&self, other: &Self) -> Self {
        let e = self.e_deg();
        let c = (0..e).map(|i| self.coeffs[i].clone() + other.coeffs[i].clone()).collect();
        Self::new(self.prime, self.precision, self.g.clone(), c)
    }

    pub fn sub(&self, other: &Self) -> Self {
        let e = self.e_deg();
        let c = (0..e).map(|i| self.coeffs[i].clone() - other.coeffs[i].clone()).collect();
        Self::new(self.prime, self.precision, self.g.clone(), c)
    }

    pub fn neg(&self) -> Self {
        let c = self.coeffs.iter().map(|c| -c.clone()).collect();
        Self::new(self.prime, self.precision, self.g.clone(), c)
    }

    pub fn mul(&self, other: &Self) -> Self {
        let e = self.e_deg();
        let mut raw = vec![Integer::zero(); 2 * e - 1];
        for i in 0..e {
            if self.coeffs[i].is_zero() {
                continue;
            }
            for j in 0..e {
                raw[i + j] = raw[i + j].clone() + self.coeffs[i].clone() * other.coeffs[j].clone();
            }
        }
        // Reduce by the monic g: π^e = −Σ_{i<e} gᵢ π^i.
        for k in (e..=2 * e - 2).rev() {
            let leading = raw[k].clone();
            if leading.is_zero() {
                continue;
            }
            for i in 0..e {
                let idx = (k - e) + i;
                raw[idx] = raw[idx].clone() - leading.clone() * self.g[i].clone();
            }
            raw[k] = Integer::zero();
        }
        raw.truncate(e);
        Self::new(self.prime, self.precision, self.g.clone(), raw)
    }

    pub fn pow(&self, mut n: u64) -> Self {
        let mut result = Self::one(self.prime, self.precision, self.g.clone());
        let mut base = self.clone();
        while n > 0 {
            if n & 1 == 1 {
                result = result.mul(&base);
            }
            n >>= 1;
            if n > 0 {
                base = base.mul(&base);
            }
        }
        result
    }

    /// Residue digit in `F_p = O_K/π`: the constant coordinate mod `p`.
    pub fn residue_digit(&self) -> i64 {
        let p = self.prime;
        let r = (self.coeffs[0].clone() % Integer::from(p)).to_i64();
        ((r % p) + p) % p
    }

    /// Multiply every coordinate by the integer `k` (mod `p^precision`).
    pub fn scale_int(&self, k: &Integer) -> Self {
        let c = self.coeffs.iter().map(|c| c.clone() * k.clone()).collect();
        Self::new(self.prime, self.precision, self.g.clone(), c)
    }

    /// Divide every coordinate by `p` exactly (caller guarantees `p | every coeff`,
    /// i.e. `v_K(self) ≥ e`).
    fn div_by_p(&self) -> Self {
        let pi = Integer::from(self.prime);
        let c = self.coeffs.iter().map(|c| c.clone() / pi.clone()).collect();
        Self::new(self.prime, self.precision, self.g.clone(), c)
    }

    /// Divide by the uniformizer `π` (caller guarantees `v_K(self) ≥ 1`). Uses
    /// `π⁻¹ = −w/g₀` with `w = Σ_{j=1}^{e} g_j π^{j−1}` and `g₀ = p·u₀`, so
    /// `self/π = −((self·w)/p)·u₀⁻¹`.
    pub fn div_by_uniformizer(&self) -> Self {
        let e = self.e_deg();
        let p = self.prime;
        let modulus = Integer::from(p).pow(self.precision);
        // w = [g_1, g_2, …, g_e] (little-endian coords of Σ g_j π^{j−1}).
        let w_coords: Vec<Integer> = (1..=e).map(|j| self.g[j].clone()).collect();
        let w = Self::new(p, self.precision, self.g.clone(), w_coords);
        let xw_over_p = self.mul(&w).div_by_p(); // (self·w)/p, valid since v_K ≥ e
        let mut u0 = (self.g[0].clone() / Integer::from(p)) % modulus.clone(); // g_0/p mod p^N
        if u0.signum() < 0 {
            u0 = u0 + modulus.clone();
        }
        let u0inv = u0.mod_inverse(&modulus).expect("g_0/p is a unit");
        xw_over_p.scale_int(&u0inv).neg()
    }

    /// `π`-adic valuation (`v_π(π)=1`, `v_π(p)=e`): `min_j (e·v_p(cⱼ) + j)`; `None`
    /// for `0`. Coefficients with `v_p ≥ precision` are treated as exact zeros.
    pub fn valuation(&self) -> Option<i64> {
        let e = self.e_deg() as i64;
        let pi = Integer::from(self.prime);
        let mut v: Option<i64> = None;
        for (j, c) in self.coeffs.iter().enumerate() {
            if c.is_zero() {
                continue;
            }
            let vj = e * c.abs().valuation(&pi) as i64 + j as i64;
            v = Some(v.map_or(vj, |cur| cur.min(vj)));
        }
        v
    }
}

// --------------------------------------------------------------------------- //
// Mixed-ramification tower  K = ℚ_q[π]/(h),  h Eisenstein over the unramified ℚ_q
// --------------------------------------------------------------------------- //

/// An element of a general local field `K = ℚ_q[π]/(h)` of degree `e·f` over `ℚ_p`,
/// where `ℚ_q` is the unramified extension of degree `f` and `h` is Eisenstein of
/// degree `e` over `ℚ_q` (the **mixed-ramification tower**). Coefficients of
/// `c₀ + c₁π + … + c_{e−1}π^{e−1}` are [`UnramifiedElement`]s of `ℚ_q`. Valuation is
/// `π`-adic: `v_π(π)=1`, `v_π(p)=e`, residue field `F_{p^f}`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TowerElement {
    pub prime: i64,
    pub precision: u32,
    /// Unramified modulus defining `ℚ_q` (lift of an irreducible over `F_p`).
    pub unram_modulus: Vec<Integer>,
    /// Eisenstein modulus `h` over `ℚ_q` (monic, little-endian, `UnramifiedElement` coeffs).
    pub h: Vec<UnramifiedElement>,
    /// Coordinates over the `ℚ_q`-basis `1, π, …, π^{e−1}`.
    pub coeffs: Vec<UnramifiedElement>,
}

impl TowerElement {
    fn e_deg(&self) -> usize {
        self.h.len() - 1
    }
    fn q_zero(&self) -> UnramifiedElement {
        UnramifiedElement::zero(self.prime, self.precision, self.unram_modulus.clone())
    }

    /// Build from `ℚ_q`-coordinates (length padded/truncated to `e`).
    pub fn new(
        prime: i64,
        precision: u32,
        unram_modulus: Vec<Integer>,
        h: Vec<UnramifiedElement>,
        mut coeffs: Vec<UnramifiedElement>,
    ) -> Self {
        let e = h.len() - 1;
        let z = UnramifiedElement::zero(prime, precision, unram_modulus.clone());
        coeffs.resize(e, z);
        TowerElement { prime, precision, unram_modulus, h, coeffs }
    }

    pub fn zero(prime: i64, precision: u32, um: Vec<Integer>, h: Vec<UnramifiedElement>) -> Self {
        let e = h.len() - 1;
        let z = UnramifiedElement::zero(prime, precision, um.clone());
        TowerElement { prime, precision, unram_modulus: um, h, coeffs: vec![z; e] }
    }

    pub fn one(prime: i64, precision: u32, um: Vec<Integer>, h: Vec<UnramifiedElement>) -> Self {
        let mut t = Self::zero(prime, precision, um.clone(), h);
        t.coeffs[0] = UnramifiedElement::one(prime, precision, um);
        t
    }

    /// The ramified uniformizer `π` (a root of `h`).
    pub fn uniformizer(prime: i64, precision: u32, um: Vec<Integer>, h: Vec<UnramifiedElement>) -> Self {
        let mut t = Self::zero(prime, precision, um.clone(), h);
        t.coeffs[1] = UnramifiedElement::one(prime, precision, um);
        t
    }

    /// Embed an element of `ℚ_q` as a constant.
    pub fn from_unram(prime: i64, precision: u32, um: Vec<Integer>, h: Vec<UnramifiedElement>, c: UnramifiedElement) -> Self {
        let mut t = Self::zero(prime, precision, um, h);
        t.coeffs[0] = c;
        t
    }

    pub fn is_zero(&self) -> bool {
        self.coeffs.iter().all(|c| c.is_zero())
    }

    pub fn add(&self, other: &Self) -> Self {
        let c = self.coeffs.iter().zip(&other.coeffs).map(|(a, b)| a.add(b)).collect();
        Self::new(self.prime, self.precision, self.unram_modulus.clone(), self.h.clone(), c)
    }

    pub fn sub(&self, other: &Self) -> Self {
        let c = self.coeffs.iter().zip(&other.coeffs).map(|(a, b)| a.sub(b)).collect();
        Self::new(self.prime, self.precision, self.unram_modulus.clone(), self.h.clone(), c)
    }

    pub fn mul(&self, other: &Self) -> Self {
        let e = self.e_deg();
        let mut raw = vec![self.q_zero(); 2 * e - 1];
        for i in 0..e {
            if self.coeffs[i].is_zero() {
                continue;
            }
            for j in 0..e {
                raw[i + j] = raw[i + j].add(&self.coeffs[i].mul(&other.coeffs[j]));
            }
        }
        // Reduce by monic h: π^e = −Σ_{i<e} h_i π^i.
        for k in (e..=2 * e - 2).rev() {
            let lead = raw[k].clone();
            if lead.is_zero() {
                continue;
            }
            for i in 0..e {
                let idx = (k - e) + i;
                raw[idx] = raw[idx].sub(&lead.mul(&self.h[i]));
            }
            raw[k] = self.q_zero();
        }
        raw.truncate(e);
        Self::new(self.prime, self.precision, self.unram_modulus.clone(), self.h.clone(), raw)
    }

    pub fn pow(&self, mut n: u64) -> Self {
        let mut result = Self::one(self.prime, self.precision, self.unram_modulus.clone(), self.h.clone());
        let mut base = self.clone();
        while n > 0 {
            if n & 1 == 1 {
                result = result.mul(&base);
            }
            n >>= 1;
            if n > 0 {
                base = base.mul(&base);
            }
        }
        result
    }

    /// `π`-adic valuation (`v_π(π)=1`, `v_π(p)=e`): `min_j (e·v_q(c_j) + j)`; `None`
    /// for `0`.
    pub fn valuation(&self) -> Option<i64> {
        let e = self.e_deg() as i64;
        self.coeffs
            .iter()
            .enumerate()
            .filter_map(|(j, c)| c.pval().map(|v| e * v as i64 + j as i64))
            .min()
    }
}

