/// An element of the unramified extension `ℤ_q = ℤ_p[ω]/(m(ω))`, truncated to
/// precision `p^N`. Coefficients are `Integer`s reduced into `[0, p^N)`; `coeffs`
/// has length `f = deg m`. `m` is a monic integer lift of an irreducible polynomial
/// over `F_p` (little-endian, `modulus[f] = 1`). Arithmetic is mod `(m, p^N)`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UnramifiedElement {
    pub prime: i64,
    /// Precision: arithmetic is modulo `p^precision`.
    pub precision: u32,
    /// Monic lift of the residue-field defining polynomial (little-endian).
    pub modulus: Vec<Integer>,
    /// Coefficients of `c₀ + c₁ω + … + c_{f−1}ω^{f−1}`, length `f`.
    pub coeffs: Vec<Integer>,
}

impl UnramifiedElement {
    fn f_deg(&self) -> usize {
        self.modulus.len() - 1
    }

    fn norm_coeffs(prime: i64, precision: u32, mut coeffs: Vec<Integer>, f: usize) -> Vec<Integer> {
        let m = Integer::from(prime).pow(precision);
        coeffs.resize(f, Integer::zero());
        for c in coeffs.iter_mut() {
            let r = c.clone() % m.clone();
            *c = if r.signum() < 0 { r + m.clone() } else { r };
        }
        coeffs
    }

    /// Build an element from raw coefficients (reduced mod `(m, p^precision)`).
    pub fn new(prime: i64, precision: u32, modulus: Vec<Integer>, coeffs: Vec<Integer>) -> Self {
        let f = modulus.len() - 1;
        let coeffs = Self::norm_coeffs(prime, precision, coeffs, f);
        UnramifiedElement { prime, precision, modulus, coeffs }
    }

    /// `0`.
    pub fn zero(prime: i64, precision: u32, modulus: Vec<Integer>) -> Self {
        let f = modulus.len() - 1;
        UnramifiedElement { prime, precision, modulus, coeffs: vec![Integer::zero(); f] }
    }

    /// `1`.
    pub fn one(prime: i64, precision: u32, modulus: Vec<Integer>) -> Self {
        Self::new(prime, precision, modulus, vec![Integer::one()])
    }

    /// The canonical generator `ω` (a lift of a residue-field generator).
    pub fn generator(prime: i64, precision: u32, modulus: Vec<Integer>) -> Self {
        Self::new(prime, precision, modulus, vec![Integer::zero(), Integer::one()])
    }

    /// Embed an integer constant.
    pub fn from_int(prime: i64, precision: u32, modulus: Vec<Integer>, n: Integer) -> Self {
        Self::new(prime, precision, modulus, vec![n])
    }

    pub fn is_zero(&self) -> bool {
        self.coeffs.iter().all(|c| c.is_zero())
    }

    pub fn add(&self, other: &Self) -> Self {
        let f = self.f_deg();
        let c: Vec<Integer> =
            (0..f).map(|i| self.coeffs[i].clone() + other.coeffs[i].clone()).collect();
        Self::new(self.prime, self.precision, self.modulus.clone(), c)
    }

    pub fn neg(&self) -> Self {
        let c: Vec<Integer> = self.coeffs.iter().map(|x| -x.clone()).collect();
        Self::new(self.prime, self.precision, self.modulus.clone(), c)
    }

    pub fn sub(&self, other: &Self) -> Self {
        self.add(&other.neg())
    }

    pub fn mul(&self, other: &Self) -> Self {
        let f = self.f_deg();
        // Schoolbook multiply into a 2f−1 buffer, then reduce by the monic modulus.
        let mut raw = vec![Integer::zero(); 2 * f - 1];
        for i in 0..f {
            if self.coeffs[i].is_zero() {
                continue;
            }
            for j in 0..f {
                raw[i + j] = raw[i + j].clone() + self.coeffs[i].clone() * other.coeffs[j].clone();
            }
        }
        // Reduce x^k (k from 2f−2 down to f) using x^f = −Σ_{i<f} m_i x^i.
        for k in (f..=2 * f - 2).rev() {
            let leading = raw[k].clone();
            if leading.is_zero() {
                continue;
            }
            for i in 0..f {
                let idx = (k - f) + i;
                raw[idx] = raw[idx].clone() - leading.clone() * self.modulus[i].clone();
            }
            raw[k] = Integer::zero();
        }
        raw.truncate(f);
        Self::new(self.prime, self.precision, self.modulus.clone(), raw)
    }

    /// Repeated-squaring power (`n ≥ 0`).
    pub fn pow(&self, mut n: u64) -> Self {
        let mut result = Self::one(self.prime, self.precision, self.modulus.clone());
        let mut base = self.clone();
        while n > 0 {
            if n & 1 == 1 {
                result = result.mul(&base);
            }
            n >>= 1;
            if n > 0 {
                base = base.mul(&base);
            }
        }
        result
    }

    /// Constant `n` embedded in this field (same prime/precision/modulus).
    fn constant(&self, n: Integer) -> Self {
        Self::from_int(self.prime, self.precision, self.modulus.clone(), n)
    }

    /// Evaluate the integer polynomial `coeffs` (little-endian) at `self` via Horner,
    /// treating coefficients as `ℤ_p` constants. Returns an element of `ℤ_q`.
    fn eval_int_poly(&self, coeffs: &[Integer]) -> Self {
        let mut result = Self::zero(self.prime, self.precision, self.modulus.clone());
        for c in coeffs.iter().rev() {
            result = result.mul(self).add(&self.constant(c.clone()));
        }
        result
    }

    /// Inverse of a residue-unit (residue ≠ 0) in `F_{p^f}`, lifted as a `ℤ_q`
    /// element with coefficients in `[0, p)` (i.e. the level-0 inverse).
    fn residue_inverse(&self) -> Self {
        let a: Vec<i64> = self.residue();
        let mbar: Vec<i64> =
            self.modulus.iter().map(|c| (c.clone() % Integer::from(self.prime)).to_i64()).collect();
        let (_g, s, _t) = fp_factor::extended_gcd(&a, &mbar, self.prime);
        // s·a ≡ gcd = 1 (mod m̄); reduce s mod m̄ and lift coefficients to ℤ.
        let sred = fp_factor::div_mod(&s, &mbar, self.prime).1;
        let coeffs: Vec<Integer> = sred.iter().map(|&c| Integer::from(c)).collect();
        Self::new(self.prime, self.precision, self.modulus.clone(), coeffs)
    }

    /// Multiplicative inverse in `ℤ_q` to full precision (self must be a unit, i.e.
    /// nonzero residue), by p-adic Newton iteration `v ← v(2 − uv)`.
    pub fn inverse(&self) -> Self {
        let mut v = self.residue_inverse();
        let two = self.constant(Integer::from(2));
        // precision doubles each step from 1; ceil(log2(precision)) + 1 steps suffice.
        let steps = 32 - (self.precision.max(1)).leading_zeros() + 1;
        for _ in 0..steps {
            let uv = self.mul(&v);
            v = v.mul(&two.sub(&uv));
        }
        v
    }

    /// The image of the generator `ω` under Frobenius: the unique root of the modulus
    /// `m` in `ℤ_q` congruent to `ω^p` mod `p`, obtained by Hensel-lifting `ω^p`.
    pub fn frobenius_generator(prime: i64, precision: u32, modulus: Vec<Integer>) -> Self {
        let f = modulus.len() - 1;
        // m'(x) (little-endian).
        let deriv: Vec<Integer> =
            (1..=f).map(|i| modulus[i].clone() * Integer::from(i as i64)).collect();
        let omega = Self::generator(prime, precision, modulus.clone());
        let mut b = omega.pow(prime as u64); // ω^p ≡ a root of m (mod p)
        let steps = 32 - (precision.max(1)).leading_zeros() + 1;
        for _ in 0..steps {
            let mb = b.eval_int_poly(&modulus); // m(b)
            let mpb = b.eval_int_poly(&deriv); // m'(b), a unit
            b = b.sub(&mb.mul(&mpb.inverse()));
        }
        b
    }

    /// The **Frobenius automorphism** `φ` of `ℚ_q/ℚ_p` applied to this element — the
    /// canonical generator of the cyclic Galois group `Gal(ℚ_q/ℚ_p) ≅ C_f`. `φ` fixes
    /// `ℚ_p`, sends `ω ↦ φ(ω)` (the Hensel-lifted root of `m`), and reduces to the
    /// residue-field Frobenius `x ↦ x^p` mod `p`. Unlike a literal `p`-th power this
    /// is a genuine field automorphism (`φ^f = id`, `φ|_{ℚ_p} = id`).
    pub fn frobenius(&self) -> Self {
        let beta = Self::frobenius_generator(self.prime, self.precision, self.modulus.clone());
        // φ(Σ cᵢ ωⁱ) = Σ cᵢ β^i  (φ fixes the ℤ_p coefficients cᵢ). Horner in β.
        let f = self.f_deg();
        let mut result = Self::zero(self.prime, self.precision, self.modulus.clone());
        for i in (0..f).rev() {
            result = result.mul(&beta).add(&self.constant(self.coeffs[i].clone()));
        }
        result
    }

    /// `p`-adic valuation `v_q(self) = v_p(self)` in the unramified `ℚ_q` (unramified,
    /// so `v_q = v_p`): the least `v_p` of the coordinates, or `None` for `0`.
    pub fn pval(&self) -> Option<u32> {
        let pi = Integer::from(self.prime);
        self.coeffs
            .iter()
            .filter(|c| !c.is_zero())
            .map(|c| c.abs().valuation(&pi))
            .min()
    }

    /// Reduction to the residue field `F_{p^f}`: the coefficient vector mod `p`
    /// (little-endian, length `f`).
    pub fn residue(&self) -> Vec<i64> {
        let p = self.prime;
        self.coeffs
            .iter()
            .map(|c| {
                let r = (c.clone() % Integer::from(p)).to_i64();
                ((r % p) + p) % p
            })
            .collect()
    }
}

/// Build a monic integer lift of an irreducible polynomial of degree `f` over `F_p`
/// to use as the unramified modulus `m`. Searches small polynomials for an
/// irreducible (sufficient for the small `f` arising as residue degrees). Returns
/// the little-endian lift (`m[f] = 1`), or `None` if none is found in the search
/// window.
pub fn unramified_modulus(p: i64, f: usize) -> Option<Vec<Integer>> {
    if f == 0 {
        return None;
    }
    if f == 1 {
        return Some(vec![Integer::zero(), Integer::one()]); // x
    }
    // Try x^f + (low-degree tail) over F_p, smallest tails first.
    let pu = p as usize;
    let total = pu.checked_pow(f as u32)?; // p^f candidate tails (coeffs of x^0..x^{f-1})
    for code in 1..total {
        let mut tail = vec![0i64; f];
        let mut c = code;
        for slot in tail.iter_mut() {
            *slot = (c % pu) as i64;
            c /= pu;
        }
        // candidate = x^f + Σ tail_i x^i  (mod p)
        let mut cand: Vec<i64> = tail.clone();
        cand.push(1);
        if is_irreducible_fp(&cand, p) {
            let lift: Vec<Integer> = cand.iter().map(|&c| Integer::from(c)).collect();
            return Some(lift);
        }
    }
    None
}

