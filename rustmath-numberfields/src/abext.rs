/// A Kummer generator `γ ∈ K^×` for the cyclic degree-`n` extension cut out by
/// `H` (requires `μ_n ⊂ K`): an element whose ideal class generates `Cl_m / H`
/// to the `n`-th power. We take a generator of a factor-base prime that is
/// nontrivial mod `H`. Returns its integral-basis coordinates, or `None` if no
/// suitable principal generator is found by the small search.
fn kummer_generator(
    f: &[Integer],
    _m: &Modulus,
    rcg: &crate::rayclass::RayClassGroup,
    n: usize,
) -> Option<Vec<Integer>> {
    use crate::classgroup::is_principal;
    use crate::ideals::ideal_mul;
    use crate::round2::maximal_order_data;
    let ord = maximal_order_data(f);
    // Look for a factor-base prime 𝔭 whose n-th power is principal: then its
    // generator γ gives K(γ^{1/n}) ramified exactly where 𝔭 sits.
    for pr in rcg.factor_base() {
        let mut pk = pr.clone();
        for _ in 1..n {
            pk = ideal_mul(&ord, &pk, pr);
        }
        if let Some(gamma) = is_principal(f, &ord, &pk) {
            return Some(gamma);
        }
    }
    None
}

