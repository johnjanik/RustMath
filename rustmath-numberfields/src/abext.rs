/// Signature `(r₁, r₂)` of a cyclic degree-`n` extension of `ℚ` given by its
/// (absolute) defining polynomial — read directly off the polynomial.
fn predicted_signature_over_q(abs_poly: &[Integer], _n: usize) -> (usize, usize) {
    signature(abs_poly)
}

/// Predicted signature of a degree-`n` abelian `L/K` from `K`'s signature and
/// the real places ramified in the conductor.
///
/// Each real place of `K` **in** the conductor `m_∞` ramifies — it becomes a
/// single complex place upstairs (its `n` extensions pair up). Each real place
/// **not** in `m_∞` stays real and splits into `n` real places. Complex places
/// of `K` each give `n` complex places of `L`.
fn predicted_signature_kummer(
    f: &[Integer],
    n: usize,
    cond: &Conductor,
) -> (usize, usize) {
    let (r1_k, r2_k) = signature(f);
    let ramified: usize = cond.real_places.len().min(r1_k);
    let unramified_real = r1_k - ramified;
    // unramified real places: each splits into n real places.
    let r1_l = unramified_real * n;
    // ramified real places: each contributes n/... extensions that are complex;
    // n real extensions collapse into n/2 complex pairs each (n even) — for the
    // signature lever the count of complex pairs from ramified real places is
    // ramified·(n/2) when n even; for n odd a real place cannot ramify in a real
    // sense, so it stays real (no sign constraint), giving ramified·n real.
    let (extra_r1, extra_r2) = if n % 2 == 0 {
        (0usize, ramified * (n / 2))
    } else {
        (ramified * n, 0usize)
    };
    let r1 = r1_l + extra_r1;
    let r2 = r2_k * n + extra_r2;
    (r1, r2)
}

/// Convenience: absolute discriminant of a field from its polynomial (for
/// cross-checking a constructed absolute model against the prediction).
pub fn absolute_disc(poly: &[Integer]) -> Integer {
    field_discriminant(poly).abs()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::artin::NormGroup;

    fn iz(v: &[i64]) -> Vec<Integer> {
        v.iter().map(|&x| Integer::from(x)).collect()
    }

    fn report(name: &str, ext: &AbelianExtension) {
        println!(
            "[abext] {}: degree={} method={:?} conductor=(f0={}, real_places={:?}) predicted_disc={} signature=(r1={},r2={}) abs_poly={:?} grh={}",
            name,
            ext.degree,
            ext.method,
            ext.conductor.finite,
            ext.conductor.real_places,
            ext.predicted_disc,
            ext.predicted_signature.0,
            ext.predicted_signature.1,
            ext.absolute_poly,
            ext.grh_conditional
        );
    }

    // ---- Cyclic cubic of conductor 7 via Gaussian periods ----
    #[test]
    fn cyclic_cubic_conductor_7_field() {
        // The exact Gaussian-period polynomial for p=7, n=3 is x³+x²−2x−1.
        let poly = gaussian_period_poly(7, 3).expect("period poly");
        // monic low-to-high; compare up to the known model x³ + x² − 2x − 1.
        assert_eq!(poly, iz(&[-1, -2, 1, 1]), "Gaussian period cubic of cond 7");
        // its discriminant is 7² = 49.
        let d = absolute_disc(&poly);
        assert_eq!(d, Integer::from(49), "disc of cyclic cubic cond 7 = 49");

        // full construction path: K = Q, m = (7), H of index 3.
        let f = iz(&[0, 1]); // Q
        let m = Modulus::finite(7);
        let rcg = ray_class_group(&f, &m).expect("rcg");
        let h = NormGroup::of_index(&rcg, 3).expect("index-3 subgroup");
        let ext = abelian_extension(&f, &m, &h).expect("extension");
        report("cyclic cubic cond 7", &ext);
        assert_eq!(ext.degree, 3);
        assert_eq!(ext.method, ConstructionMethod::GaussianPeriods);
        assert_eq!(ext.predicted_disc, Integer::from(49));
        // the absolute (polredabs) model must itself have discriminant 49.
        let abs = ext.absolute_poly.as_ref().expect("abs poly");
        assert_eq!(absolute_disc(abs), Integer::from(49));
        // totally real cyclic cubic: signature (3,0).
        assert_eq!(ext.predicted_signature, (3, 0));
    }

    // ---- Q(√5) (conductor 5) via Gaussian periods (n = 2) ----
    #[test]
    fn quadratic_conductor_5_field() {
        // p=5, n=2: periods give x² + x − 1 (a generator of Q(√5)); disc 5.
        let poly = gaussian_period_poly(5, 2).expect("period poly");
        let d = absolute_disc(&poly);
        assert_eq!(d, Integer::from(5), "disc Q(√5) = 5");

        let f = iz(&[0, 1]); // Q
        let m = Modulus::finite(5);
        let rcg = ray_class_group(&f, &m).expect("rcg");
        let h = NormGroup::of_index(&rcg, 2).expect("index-2 subgroup");
        let ext = abelian_extension(&f, &m, &h).expect("extension");
        report("Q(√5)/Q cond 5", &ext);
        assert_eq!(ext.degree, 2);
        assert_eq!(ext.predicted_disc, Integer::from(5));
        let abs = ext.absolute_poly.as_ref().expect("abs poly");
        assert_eq!(absolute_disc(abs), Integer::from(5));
        // real quadratic ⇒ (2,0).
        assert_eq!(ext.predicted_signature, (2, 0));
    }

    // ---- Cyclic quartic of conductor 5: x⁴+x³+x²+x+1 → Q(ζ_5), degree 4 ----
    #[test]
    fn cyclic_quartic_conductor_5() {
        // p=5, n=4: the full Q(ζ_5), period poly = the cyclotomic x⁴+x³+x²+x+1.
        let poly = gaussian_period_poly(5, 4).expect("period poly");
        assert_eq!(poly, iz(&[1, 1, 1, 1, 1]), "Q(ζ_5) cyclotomic poly");
        // disc(Q(ζ_5)) = 125 = 5³.
        let d = absolute_disc(&poly);
        assert_eq!(d, Integer::from(125), "disc Q(ζ_5) = 5³ = 125");
        // conductor–discriminant: |D| = 1·∏ N(f(χ)) = 5·5·5 (three nontrivial
        // characters of conductor 5) = 125.
        let predicted = crate::disc_score::disc_from_conductors(
            0.0,
            &[Integer::from(1), Integer::from(5), Integer::from(5), Integer::from(5)],
        );
        assert!((predicted - 125.0_f64.ln()).abs() < 1e-9);
    }

    // ---- Kummer route selection over Q(i) (μ_4 ⊂ K is not μ_n for n=2? μ_2⊂K) ----
    #[test]
    fn kummer_route_over_qi() {
        // K = Q(i) contains μ_4 ⊃ μ_2. A degree-2 layer can go Kummer (n=2 | 4).
        let f = iz(&[1, 0, 1]); // Q(i)
        let m = Modulus::finite(5);
        let rcg = ray_class_group(&f, &m).expect("rcg");
        // Cl_m for Q(i), m=(5) has order 4 (from rayclass tests). Take index-2 H.
        if let Some(h) = NormGroup::of_index(&rcg, 2) {
            if let Some(ext) = abelian_extension(&f, &m, &h) {
                report("Kummer over Q(i)", &ext);
                // route should be Kummer (μ_2 ⊂ Q(i)); generator may or may not be
                // found by the small search, but the method is Kummer.
                assert_eq!(ext.degree, 2);
                assert_eq!(ext.method, ConstructionMethod::Kummer);
            }
        }
    }
}
