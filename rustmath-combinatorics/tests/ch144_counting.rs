#[test]
fn sibling_counts_do_not_truncate() {
    use rustmath_combinatorics::enumeration::stars_and_bars;
    use rustmath_combinatorics::path_tableaux::count_lattice_paths_ne;
    use rustmath_combinatorics::subset::count_k_subsets;
    // gp binomial(2^32, 1) = 4294967296 (HEAD formed m + n in u32).
    assert_eq!(count_lattice_paths_ne(u32::MAX, 1), Integer::from(4294967296u64));
    // gp polcoef(prod(i=1,5,1/(1-x^i))+O(x^101),100) = 46262
    assert_eq!(count_partitions_with_max_parts(100, 5), 46262);
    #[cfg(target_pointer_width = "64")]
    {
        // gp binomial(2^32+2, 2) = 9223372043297226753 (HEAD truncated n to 2: 1).
        assert_eq!(count_k_subsets(4294967298, 2), int("9223372043297226753"));
        // gp binomial(2^32+1, 1) = 4294967297 (HEAD truncated: 1).
        assert_eq!(stars_and_bars(4294967296, 2), 4294967297);
        // gp numbpart(416) = 17873792969689876004
        assert_eq!(count_partitions_with_max_parts(416, 416), 17873792969689876004);
    }
}

