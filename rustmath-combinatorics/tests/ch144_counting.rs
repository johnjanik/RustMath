//! Classical counting functions against PARI/GP.
//!
//! MAGMA Handbook ch. 144 §144.2 (digest
//! `rustmath-lava/docs/Chapter_144_Enumerative_Combinatorics.md:34-53`) and ch. 18 §18.8
//! (`Chapter_18_Ring_of_Integers.md:261-275`): `Factorial`, `NumberOfPermutations`,
//! `Binomial`, `Multinomial`, `Fibonacci`, `Lucas`, `GeneralizedFibonacciNumber`, `Catalan`,
//! `StirlingFirst`, `StirlingSecond`, `Bell`, `EulerianNumber`; the Pochhammer symbol of
//! ch. 49 (`Chapter_49_Power_Laurent_and_Puiseux_Series.md:292`). The Motzkin, Schroder and
//! derangement numbers are not MAGMA intrinsics (OEIS A001006, A006318, A000166).
//!
//! The fixture `tests/data/ch144_counting.csv` (116 rows, columns `fn,a,b,sign,residue,bits`,
//! residue = value mod 2^127 - 1 in [0, M), bits = bit length of |value|) is generated by
//! PARI/GP 2.15:
//!
//! ```text
//! gp -q tests/data/gen_counting.gp > tests/data/ch144_counting.csv
//! ```
//!
//! Each other reference value quotes its gp command next to it.

use rustmath_combinatorics::*;
use rustmath_integers::Integer;
use rustmath_polynomials::UnivariatePolynomial;
use rustmath_rationals::Rational;

const FIXTURE: &str = include_str!("data/ch144_counting.csv");

/// M = 2^127 - 1.
fn modulus() -> Integer {
    Integer::from(2).pow(127) - Integer::one()
}

/// (sign, residue mod M in [0, M), bit length of |v|), as in the fixture.
fn signature(v: &Integer) -> (i8, String, u64) {
    let m = modulus();
    let mut r = v.clone() % m.clone();
    if r.signum() < 0 {
        r = r + m;
    }
    (v.signum(), r.to_string(), v.bit_length())
}

fn int(s: &str) -> Integer {
    Integer::from_decimal_str(s).unwrap()
}

#[test]
fn counting_fixture_agrees_with_pari() {
    let mut rows = 0;
    for line in FIXTURE.lines().skip(1) {
        let c: Vec<&str> = line.split(',').collect();
        assert_eq!(c.len(), 6, "{line}");
        let (f, a, b) = (c[0], c[1], c[2]);
        let want: (i8, String, u64) = (c[3].parse().unwrap(), c[4].to_string(), c[5].parse().unwrap());
        let u = |s: &str| -> u32 { s.parse().unwrap() };
        let mut values: Vec<Integer> = Vec::new();
        match f {
            "catalan" => values.push(catalan(u(a))),
            "fibonacci" | "lucas" => {
                let n: i64 = a.parse().unwrap();
                if f == "fibonacci" {
                    values.push(fibonacci_signed(n));
                    if n >= 0 {
                        values.push(fibonacci(n as u32));
                    }
                } else {
                    values.push(lucas_signed(n));
                    if n >= 0 {
                        values.push(lucas(n as u32));
                    }
                }
            }
            "bell" => values.push(bell_number(u(a))),
            "stirling1" => values.push(stirling_first(u(a), u(b))),
            "stirling2" => values.push(stirling_second(u(a), u(b))),
            "eulerian" => values.push(eulerian(u(a), u(b))),
            "motzkin" => values.push(motzkin(u(a))),
            "schroder_large" => values.push(schroder_large(u(a))),
            "schroder_small" => values.push(schroder_small(u(a))),
            "derangements" => values.push(count_derangements(u(a))),
            "factorial" => values.push(factorial(u(a))),
            "falling_factorial" | "rising_factorial" => {
                let x = int(a);
                let k: u64 = b.parse().unwrap();
                let u32_x = a.parse::<u32>().ok();
                if f == "falling_factorial" {
                    values.push(falling_factorial_integer(&x, k));
                    if let Some(n) = u32_x {
                        values.push(falling_factorial(n, k as u32));
                        values.push(number_of_permutations(n, k as u32));
                    }
                } else {
                    values.push(rising_factorial_integer(&x, k));
                    if let Some(n) = u32_x {
                        values.push(rising_factorial(n, k as u32));
                    }
                }
            }
            "binomial" => values.push(binomial(u(a), u(b))),
            other => panic!("unknown fixture row {other}"),
        }
        for v in &values {
            assert_eq!(signature(v), want, "{line}");
        }
        rows += 1;
    }
    assert_eq!(rows, 116);
}

#[test]
fn rising_factorial_u32_does_not_overflow() {
    // gp (2^32-1)*2^32 = 18446744069414584320; HEAD formed n + 1 in u32 (0 in release).
    assert_eq!(rising_factorial(4294967295, 2), Integer::from(18446744069414584320u64));
}

#[test]
fn multinomial_sum_does_not_wrap() {
    // The u32 sum of HEAD wrapped: 2^32 + 1 = 1 and 2^32 = 0.
    assert_eq!(multinomial(1, &[u32::MAX, 2]), Integer::zero());
    assert_eq!(multinomial(0, &[1 << 31, 1 << 31]), Integer::zero());
    // gp binomial(2^32-1, 1) = 4294967295 (HEAD computed (2^32-1)!).
    assert_eq!(multinomial(u32::MAX, &[u32::MAX - 1, 1]), Integer::from(4294967295u64));
    // gp 30!/(1!*2!*3!*4!*5!*6!*9!) = 29375875019771280000
    assert_eq!(multinomial(30, &[1, 2, 3, 4, 5, 6, 9]), int("29375875019771280000"));
    // gp v = 10000!/(2500!^4): lift(Mod(v, 2^127-1)), logint(v, 2) + 1
    assert_eq!(
        signature(&multinomial(10000, &[2500; 4])),
        (1, "129213650714704638181892182263183187668".to_string(), 19981)
    );
    assert_eq!(multinomial(5, &[2, 2]), Integer::zero());
}

#[test]
fn catalan_satisfies_the_magma_recursion() {
    // MAGMA ch. 144 (digest :42): C_0 = 1, C_(n+1) = C_n (4n + 2) / (n + 2).
    assert_eq!(catalan(0), Integer::one());
    for n in 0..=400u32 {
        assert_eq!(
            Integer::from(n + 2) * catalan(n + 1),
            Integer::from(4 * n + 2) * catalan(n),
            "n = {n}"
        );
    }
}

/// G_n by the plain two-term recurrence, forward and backward (the HEAD loop).
fn gfib_loop(g0: i64, g1: i64, n: i64) -> Integer {
    let (mut lo, mut hi) = (Integer::from(g0), Integer::from(g1)); // (G_m, G_(m+1)), m = 0
    if n >= 0 {
        for _ in 0..n {
            let next = lo.clone() + hi.clone();
            lo = std::mem::replace(&mut hi, next);
        }
        lo
    } else {
        for _ in 0..(-n) {
            let prev = hi.clone() - lo.clone();
            hi = std::mem::replace(&mut lo, prev);
        }
        lo
    }
}

#[test]
fn fibonacci_doubling_matches_the_recurrence() {
    for (g0, g1) in [(0, 1), (2, 1), (3, 5), (-7, 11)] {
        for n in -300i64..=300 {
            assert_eq!(generalized_fibonacci_number(g0, g1, n), gfib_loop(g0, g1, n), "({g0}, {g1}, {n})");
        }
    }
    for n in -300i64..=300 {
        assert_eq!(fibonacci_signed(n), gfib_loop(0, 1, n));
        assert_eq!(lucas_signed(n), gfib_loop(2, 1, n));
    }
    for n in 0..=300u32 {
        assert_eq!(fibonacci(n), fibonacci_signed(i64::from(n)));
        assert_eq!(lucas(n), lucas_signed(i64::from(n)));
    }
    // gp v = 3*fibonacci(99999)+5*fibonacci(100000): lift(Mod(v, 2^127-1)), sign(v)
    let v = generalized_fibonacci_number(3, 5, 100000);
    assert_eq!(signature(&v).0, 1);
    assert_eq!(signature(&v).1, "97280742721680003836121413480268365629");
    // gp v = 3*fibonacci(-100001)+5*fibonacci(-100000)
    let v = generalized_fibonacci_number(3, 5, -100000);
    assert_eq!(signature(&v).0, -1);
    assert_eq!(signature(&v).1, "103771081190773177687255222800512674149");
    // gp -7*fibonacci(-11)+11*fibonacci(-10) = -1228
    assert_eq!(generalized_fibonacci_number(-7, 11, -10), Integer::from(-1228));
    // i64::MIN is accepted (its absolute value is formed as a u64); only check n = -1, -2.
    assert_eq!(generalized_fibonacci_number(0, 1, -1), Integer::one());
    assert_eq!(generalized_fibonacci_number(0, 1, -2), Integer::from(-1));
}

/// HEAD's (n + 1) x (k + 1) tables (lib.rs at dc367a2), copied as the reference.
fn table_stirling1(n: u32, k: u32) -> Integer {
    if n == 0 && k == 0 {
        return Integer::one();
    }
    if n == 0 || k == 0 || k > n {
        return Integer::zero();
    }
    if k == n {
        return Integer::one();
    }
    let mut dp = vec![vec![Integer::zero(); (k + 1) as usize]; (n + 1) as usize];
    dp[0][0] = Integer::one();
    for i in 1..=n as usize {
        for j in 1..=k.min(i as u32) as usize {
            if j == i {
                dp[i][j] = Integer::one();
            } else {
                dp[i][j] = Integer::from((i - 1) as u32) * dp[i - 1][j].clone() + dp[i - 1][j - 1].clone();
            }
        }
    }
    dp[n as usize][k as usize].clone()
}

fn table_stirling2(n: u32, k: u32) -> Integer {
    if n == 0 && k == 0 {
        return Integer::one();
    }
    if n == 0 || k == 0 || k > n {
        return Integer::zero();
    }
    if k == 1 || k == n {
        return Integer::one();
    }
    let mut dp = vec![vec![Integer::zero(); (k + 1) as usize]; (n + 1) as usize];
    dp[0][0] = Integer::one();
    for i in 1..=n as usize {
        for j in 1..=k.min(i as u32) as usize {
            if j == 1 || j == i {
                dp[i][j] = Integer::one();
            } else {
                dp[i][j] = Integer::from(j as u32) * dp[i - 1][j].clone() + dp[i - 1][j - 1].clone();
            }
        }
    }
    dp[n as usize][k as usize].clone()
}

fn table_eulerian(n: u32, k: u32) -> Integer {
    if n == 0 && k == 0 {
        return Integer::one();
    }
    if k >= n {
        return Integer::zero();
    }
    if k == 0 {
        return Integer::one();
    }
    let mut dp = vec![vec![Integer::zero(); (k + 1) as usize]; (n + 1) as usize];
    dp[0][0] = Integer::one();
    for i in 1..=n as usize {
        for j in 0..=k.min((i - 1) as u32) as usize {
            if j == 0 {
                dp[i][j] = Integer::one();
            } else {
                let t1 = Integer::from((j + 1) as u32) * dp[i - 1][j].clone();
                let t2 = Integer::from((i as u32) - (j as u32)) * dp[i - 1][j - 1].clone();
                dp[i][j] = t1 + t2;
            }
        }
    }
    dp[n as usize][k as usize].clone()
}

