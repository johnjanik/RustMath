#[test]
fn falling_rising_integer_values() {
    // Sage doc examples (sage.arith.misc): falling_factorial(10, 3) = 720,
    // falling_factorial(10, 10) = 3628800, rising_factorial(10, 3) = 1320
    // (gp prod(i=0,2,10-i), prod(i=0,9,10-i), prod(i=0,2,10+i)).
    let i = Integer::from;
    assert_eq!(falling_factorial_integer(&i(10), 3), i(720));
    assert_eq!(falling_factorial_integer(&i(10), 10), i(3628800));
    assert_eq!(rising_factorial_integer(&i(10), 3), i(1320));
    for x in [-3, 0, 5] {
        assert_eq!(falling_factorial_integer(&i(x), 0), Integer::one());
        assert_eq!(rising_factorial_integer(&i(x), 0), Integer::one());
    }
    assert_eq!(falling_factorial_integer(&i(5), 6), Integer::zero());
    assert_eq!(rising_factorial_integer(&i(0), 3), Integer::zero());
    // gp prod(i=0,5,-5+i) = 0, prod(i=0,4,-5+i) = -120
    assert_eq!(rising_factorial_integer(&i(-5), 6), Integer::zero());
    assert_eq!(rising_factorial_integer(&i(-5), 5), i(-120));
}

#[test]
fn falling_rising_in_a_polynomial_ring() {
    // Sage: falling_factorial(x, 4) = x^4 - 6x^3 + 11x^2 - 6x and
    // rising_factorial(x, 4) = x^4 + 6x^3 + 11x^2 + 6x (gp prod(i=0,3,x-i), prod(i=0,3,x+i)).
    let x: UnivariatePolynomial<Integer> = UnivariatePolynomial::var();
    let one = UnivariatePolynomial::constant(Integer::one());
    let i = Integer::from;
    let f = falling_factorial_in(&x, 4, &one);
    assert_eq!(f.coefficients(), &[i(0), i(-6), i(11), i(-6), i(1)]);
    let r = rising_factorial_in(&x, 4, &one);
    assert_eq!(r.coefficients(), &[i(0), i(6), i(11), i(6), i(1)]);
    assert_eq!(falling_factorial_in(&x, 0, &one), one);
    // gp prod(i=0,2,1/2-i) = 3/8, prod(i=0,2,1/2+i) = 15/8
    let half = Rational::new(1, 2).unwrap();
    let q1 = Rational::from_integer(1);
    assert_eq!(falling_factorial_in(&half, 3, &q1), Rational::new(3, 8).unwrap());
    assert_eq!(rising_factorial_in(&half, 3, &q1), Rational::new(15, 8).unwrap());
    // A zero factor ends the product early: 3 (3-1) (3-2) (3-3) ... = 0.
    assert_eq!(falling_factorial_in(&i(3), 10, &Integer::one()), Integer::zero());
}

