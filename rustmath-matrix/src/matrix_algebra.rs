//! Matrix algebras `Mₙ(F)` and finitely generated subalgebras (MAGMA ch. 83).
//!
//! MAGMA source: Handbook chapter 83 (Matrix Algebras), §83.2
//! (`MatrixAlgebra(S, n)`, `MatrixAlgebra<S, n | L>`), §83.3
//! (`Generators`, `Ngens`) and §83.9 (`Dimension`, `Basis`, `BasisElement`).
//!
//! This module is **purely additive** and supplies two things:
//!
//! * [`MatN<F, N>`] — a *fixed size* `N×N` matrix element that implements the
//!   `rustmath-core` [`Algebra<F>`](rustmath_core::Algebra) tower
//!   (`Ring` + `Module<F>` + `VectorSpace<F>` + `Algebra<F>`). The const generic
//!   makes the static `Ring::zero()`/`one()` and `VectorSpace::dimension()`
//!   well-defined and every operator total — the contract those traits require.
//! * [`MatrixAlgebra<F>`] — a runtime [`Parent`] modelling either the full
//!   algebra `Mₙ(F)` or the unital `F`-subalgebra generated by a list of `n×n`
//!   matrices. It exposes `Dimension`, `Basis`, `BasisElement`, `Generators` and
//!   `Ngens`; the generated case computes its dimension/basis by closing the
//!   generators under multiplication (the standard "spinning" over `F`).

use crate::Matrix;
use rustmath_core::parent::{Parent, ParentWithBasis, ParentWithGenerators};
use rustmath_core::{
    Algebra, CommutativeRing, Field, MathError, Module, Result, Ring, VectorSpace as CoreVectorSpace,
};
use std::fmt;
use std::ops::{Add, Mul, Neg, Sub};

/// An `N × N` matrix over a field `F`, as an element of the matrix algebra
/// `Mₙ(F)`. All arithmetic is total (the shape is fixed by the const generic),
/// so this type implements the full core [`Algebra<F>`] tower.
#[derive(Clone, Debug, PartialEq)]
pub struct MatN<F: Field, const N: usize> {
    data: Vec<F>, // invariant: length N*N, row-major
}

impl<F: Field, const N: usize> MatN<F, N> {
    /// Build from a row-major length-`N²` array.
    pub fn from_flat(data: Vec<F>) -> Result<Self> {
        if data.len() != N * N {
            return Err(MathError::InvalidArgument(format!(
                "MatN<_, {N}> needs {} entries, got {}",
                N * N,
                data.len()
            )));
        }
        Ok(MatN { data })
    }

    /// Convert from a dynamic [`Matrix`] (must be `N × N`).
    pub fn from_matrix(m: &Matrix<F>) -> Result<Self> {
        if m.rows() != N || m.cols() != N {
            return Err(MathError::InvalidArgument(format!(
                "matrix is {}x{}, expected {N}x{N}",
                m.rows(),
                m.cols()
            )));
        }
        Ok(MatN {
            data: m.data().to_vec(),
        })
    }

    /// Convert to a dynamic [`Matrix`].
    pub fn to_matrix(&self) -> Matrix<F> {
        Matrix::from_vec(N, N, self.data.clone()).expect("shape is consistent")
    }

    /// Entry access.
    pub fn get(&self, i: usize, j: usize) -> &F {
        &self.data[i * N + j]
    }

    /// The trace (sum of the diagonal).
    pub fn trace(&self) -> F {
        let mut s = F::zero();
        for i in 0..N {
            s = s + self.data[i * N + i].clone();
        }
        s
    }
}

impl<F: Field, const N: usize> fmt::Display for MatN<F, N> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "MatN{N}[")?;
        for i in 0..N {
            if i > 0 {
                write!(f, "; ")?;
            }
            for j in 0..N {
                if j > 0 {
                    write!(f, ", ")?;
                }
                write!(f, "{}", self.data[i * N + j])?;
            }
        }
        write!(f, "]")
    }
}

impl<F: Field, const N: usize> Add for MatN<F, N> {
    type Output = Self;
    fn add(self, rhs: Self) -> Self {
        MatN {
            data: self
                .data
                .into_iter()
                .zip(rhs.data)
                .map(|(a, b)| a + b)
                .collect(),
        }
    }
}

impl<F: Field, const N: usize> Sub for MatN<F, N> {
    type Output = Self;
    fn sub(self, rhs: Self) -> Self {
        MatN {
            data: self
                .data
                .into_iter()
                .zip(rhs.data)
                .map(|(a, b)| a - b)
                .collect(),
        }
    }
}

impl<F: Field, const N: usize> Neg for MatN<F, N> {
    type Output = Self;
    fn neg(self) -> Self {
        MatN {
            data: self.data.into_iter().map(|a| -a).collect(),
        }
    }
}

impl<F: Field, const N: usize> Mul for MatN<F, N> {
    type Output = Self;
    fn mul(self, rhs: Self) -> Self {
        let mut data = vec![F::zero(); N * N];
        for i in 0..N {
            for j in 0..N {
                let mut acc = F::zero();
                for k in 0..N {
                    acc = acc + self.data[i * N + k].clone() * rhs.data[k * N + j].clone();
                }
                data[i * N + j] = acc;
            }
        }
        MatN { data }
    }
}

impl<F: Field, const N: usize> Ring for MatN<F, N> {
    fn zero() -> Self {
        MatN {
            data: vec![F::zero(); N * N],
        }
    }
    fn one() -> Self {
        let mut data = vec![F::zero(); N * N];
        for i in 0..N {
            data[i * N + i] = F::one();
        }
        MatN { data }
    }
    fn is_zero(&self) -> bool {
        self.data.iter().all(|x| x.is_zero())
    }
    fn is_one(&self) -> bool {
        for i in 0..N {
            for j in 0..N {
                let want = if i == j { F::one() } else { F::zero() };
                if self.data[i * N + j] != want {
                    return false;
                }
            }
        }
        true
    }
}

impl<F: Field, const N: usize> Module<F> for MatN<F, N> {
    fn scalar_mul(&self, scalar: &F) -> Self {
        MatN {
            data: self.data.iter().map(|a| a.clone() * scalar.clone()).collect(),
        }
    }
    fn zero() -> Self {
        <Self as Ring>::zero()
    }
    fn is_zero(&self) -> bool {
        <Self as Ring>::is_zero(self)
    }
}

impl<F: Field, const N: usize> CoreVectorSpace<F> for MatN<F, N> {
    fn dimension() -> Option<usize> {
        Some(N * N)
    }
}

// `rustmath_core::Algebra<F>` — a matrix algebra is the archetypal
// finite-dimensional associative algebra.
impl<F: Field, const N: usize> Algebra<F> for MatN<F, N> {
    fn scalar_mul(&self, scalar: &F) -> Self {
        Module::scalar_mul(self, scalar)
    }

    fn dimension(&self) -> Option<usize> {
        Some(N * N)
    }
}

// A matrix algebra is a (non-commutative) ring; we do NOT claim CommutativeRing
// in general. The marker below is available only when the caller knows N ≤ 1.
impl<F: Field> CommutativeRing for MatN<F, 1> {}

