//! The ATLAS character table of M23 as data, in exact arithmetic, and the class structure
//! constants.
//!
//! MAGMA: ch. 91 (`CharacterTable`, `InnerProduct`, `StructureConstant`, `PowerMap`); digest
//! `rustmath-lava/docs/Chapter_91_Characters_of_Finite_Groups.md`. RustMath has no
//! Dixon-Schneider algorithm (follow-up WPP-6), so the table is data.
//!
//! Sources:
//! - Conway, Curtis, Norton, Parker, Wilson, *ATLAS of Finite Groups* (1985), M23, p. 71.
//! - GAP 4.12.1 with CTblLib 1.3.7, `CharacterTable("M23")`. The file
//!   `data/m23/m23_atlas_table.json` is written by `data/m23/m23_atlas_table.g` (command in its
//!   header; sha256 `f9503e809aef25c369cf2b40c816bf72e23876d8162343cb75166e8d0f5196eb`).
//! - Frobenius; Serre, *Topics in Galois Theory* (1992), 7.2: the normalized structure
//!   constant `n(C1, C2, C3) = |C1| |C2| |C3| / |G|^2 * sum_chi chi(c1) chi(c2) chi(c3) / chi(1)`,
//!   the number of triples `(g1, g2, g3)` in `C1 x C2 x C3` with `g1 g2 g3 = 1`, divided by `|G|`.
//!
//! A value is stored as `[x, y, d]`, meaning `x + y b_d` with the ATLAS irrationality
//! `b_d = (-1 + sqrt(-d)) / 2`, `d` in `{7, 11, 15, 23}` (`[x, 0, 1]` for a rational value).
//! [`AtlasNumber`] is an element of `K = Q(sqrt(-7), sqrt(-11), sqrt(-15), sqrt(-23))` (degree
//! 16) with [`Rational`] coordinates. No lower crate has an exact quadratic or cyclotomic type,
//! and `rustmath-numberfields` depends on this crate, so this is a field element type for the
//! table, not a numeric wrapper.
//!
//! The class order of the file is GAP's column order, which is the order of
//! [`M23Class::ALL`]. [`AtlasTable::check_against`] matches it with RustMath's classes (element
//! orders, class sizes, centralizer orders, all stored power maps, the permutation character).
//! These data fix the columns up to the table automorphisms (order 16, generated by
//! `(16,17)`, `(14,15)`, `(10,11)`, `(7,8)(12,13)` in GAP's 1-based numbering). Each is a Galois
//! map `g -> g^k`, so every structure constant is invariant under them.

