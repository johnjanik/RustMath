use std::ops::{Add, Mul, Neg, Sub};
use std::sync::OnceLock;

use rustmath_complex::Complex;
use rustmath_rationals::Rational;

use super::classes::{ClassIdentifier, M23Class};
use super::group::{fixed_mask, order, power, M23, M23_ORDER};
use crate::representation::{Character, CharacterTable};

/// The four `d` of the ATLAS irrationalities `b_d`.
const DS: [i64; 4] = [7, 11, 15, 23];

/// An element of `Q(s7, s11, s15, s23)` with `s_d^2 = -d`: 16 rational coordinates on the basis
/// `prod_{i in S} s_{d_i}`, indexed by the subsets `S` of the four (bit `i` for `d_i`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AtlasNumber {
    c: [Rational; 16],
}

impl AtlasNumber {
    /// 0.
    pub fn zero() -> AtlasNumber {
        AtlasNumber {
            c: std::array::from_fn(|_| Rational::from(0i64)),
        }
    }

    /// A rational number.
    pub fn from_rational(q: Rational) -> AtlasNumber {
        let mut a = AtlasNumber::zero();
        a.c[0] = q;
        a
    }

    /// `x + y b_d` with `b_d = (-1 + sqrt(-d)) / 2`. `d = 1` means a rational value and needs
    /// `y = 0`. `Err` for any other `d`.
    pub fn from_atlas(x: i64, y: i64, d: u32) -> Result<AtlasNumber, String> {
        let mut a = AtlasNumber::from_rational(Rational::from(x));
        if d == 1 {
            if y != 0 {
                return Err(format!("[{x}, {y}, 1]: a rational value needs y = 0"));
            }
            return Ok(a);
        }
        let i = DS
            .iter()
            .position(|&e| e == d as i64)
            .ok_or_else(|| format!("[{x}, {y}, {d}]: d is not 7, 11, 15 or 23"))?;
        let half = Rational::new(y, 2).map_err(|e| format!("{e:?}"))?;
        a.c[0] = &a.c[0] - &half;
        a.c[1 << i] = half;
        Ok(a)
    }

    /// The coordinates on the basis `prod_{i in S} s_{d_i}`.
    pub fn coordinates(&self) -> &[Rational; 16] {
        &self.c
    }

    /// Complex conjugation: `s_d -> -s_d`, a sign change on the odd subsets.
    pub fn conj(&self) -> AtlasNumber {
        AtlasNumber {
            c: std::array::from_fn(|i| {
                if (i as u32).count_ones() % 2 == 1 {
                    -&self.c[i]
                } else {
                    self.c[i].clone()
                }
            }),
        }
    }

    /// The value if it is rational, else `None`.
    pub fn rational_part(&self) -> Option<Rational> {
        let zero = Rational::from(0i64);
        if self.c[1..].iter().all(|x| *x == zero) {
            Some(self.c[0].clone())
        } else {
            None
        }
    }

    /// The product with a rational number.
    pub fn scale(&self, q: &Rational) -> AtlasNumber {
        AtlasNumber {
            c: std::array::from_fn(|i| &self.c[i] * q),
        }
    }

    /// The complex value in `f64` (`s_d = i sqrt(d)`), for the float table of T-215.
    pub fn to_complex_f64(&self) -> Complex {
        let (mut re, mut im) = (0.0f64, 0.0f64);
        for (s, q) in self.c.iter().enumerate() {
            let x = q.to_f64().unwrap_or(f64::NAN);
            if x == 0.0 {
                continue;
            }
            let mut mag = x;
            for (i, &d) in DS.iter().enumerate() {
                if (s >> i) & 1 == 1 {
                    mag *= (d as f64).sqrt();
                }
            }
            // i^|S|
            match (s as u32).count_ones() % 4 {
                0 => re += mag,
                1 => im += mag,
                2 => re -= mag,
                _ => im -= mag,
            }
        }
        Complex::new(re, im)
    }
}

impl Add for &AtlasNumber {
    type Output = AtlasNumber;
    fn add(self, o: &AtlasNumber) -> AtlasNumber {
        AtlasNumber {
            c: std::array::from_fn(|i| &self.c[i] + &o.c[i]),
        }
    }
}

impl Sub for &AtlasNumber {
    type Output = AtlasNumber;
    fn sub(self, o: &AtlasNumber) -> AtlasNumber {
        AtlasNumber {
            c: std::array::from_fn(|i| &self.c[i] - &o.c[i]),
        }
    }
}

impl Neg for &AtlasNumber {
    type Output = AtlasNumber;
    fn neg(self) -> AtlasNumber {
        AtlasNumber {
            c: std::array::from_fn(|i| -&self.c[i]),
        }
    }
}

impl Mul for &AtlasNumber {
    type Output = AtlasNumber;
    /// `s^S s^T = s^(S xor T) prod_{i in S and T} (-d_i)`.
    fn mul(self, o: &AtlasNumber) -> AtlasNumber {
        let zero = Rational::from(0i64);
        let mut r = AtlasNumber::zero();
        for a in 0..16 {
            if self.c[a] == zero {
                continue;
            }
            for b in 0..16 {
                if o.c[b] == zero {
                    continue;
                }
                let mut c = &self.c[a] * &o.c[b];
                for (i, &d) in DS.iter().enumerate() {
                    if (a >> i) & 1 == 1 && (b >> i) & 1 == 1 {
                        c = &c * &Rational::from(-d);
                    }
                }
                r.c[a ^ b] = &r.c[a ^ b] + &c;
            }
        }
        r
    }
}

impl Add for AtlasNumber {
    type Output = AtlasNumber;
    fn add(self, o: AtlasNumber) -> AtlasNumber {
        &self + &o
    }
}

impl Sub for AtlasNumber {
    type Output = AtlasNumber;
    fn sub(self, o: AtlasNumber) -> AtlasNumber {
        &self - &o
    }
}

impl Mul for AtlasNumber {
    type Output = AtlasNumber;
    fn mul(self, o: AtlasNumber) -> AtlasNumber {
        &self * &o
    }
}

/// The embedded table file.
const TABLE_JSON: &str = include_str!("../../data/m23/m23_atlas_table.json");

/// The ATLAS character table of M23 (17 irreducibles on 17 classes, ATLAS order).
#[derive(Clone, Debug)]
pub struct AtlasTable {
    source: String,
    orders: [u32; 17],
    centralizer_orders: [u64; 17],
    class_sizes: [u64; 17],
    power_maps: Vec<(i64, [M23Class; 17])>,
    permutation_character: [i64; 17],
    irreducibles: Vec<[AtlasNumber; 17]>,
}

fn int_list(j: &serde_json::Value, key: &str) -> Result<Vec<i64>, String> {
    j.get(key)
        .and_then(|v| v.as_array())
        .ok_or_else(|| format!("no list {key}"))?
        .iter()
        .map(|v| v.as_i64().ok_or_else(|| format!("{key}: not an integer")))
        .collect()
}

/// [`int_list`] converted to `T` (`u32` or `u64`); `Err` naming the field for a negative or
/// too large entry.
fn unsigned_list<T: TryFrom<i64>>(j: &serde_json::Value, key: &str) -> Result<Vec<T>, String> {
    int_list(j, key)?
        .into_iter()
        .map(|x| T::try_from(x).map_err(|_| format!("{key}: entry {x} out of range")))
        .collect()
}

fn seventeen<T: Copy + Default>(v: Vec<T>, key: &str) -> Result<[T; 17], String> {
    if v.len() != 17 {
        return Err(format!("{key}: {} entries instead of 17", v.len()));
    }
    let mut a = [T::default(); 17];
    a.copy_from_slice(&v);
    Ok(a)
}

impl AtlasTable {
    /// The embedded table (`data/m23/m23_atlas_table.json`), parsed once.
    ///
    /// # Panics
    ///
    /// If the embedded file does not parse, which is a defect of the build (the file is
    /// checked by `tests/m23_atlas.rs`).
    pub fn m23() -> &'static AtlasTable {
        static TABLE: OnceLock<AtlasTable> = OnceLock::new();
        TABLE.get_or_init(|| AtlasTable::parse(TABLE_JSON).expect("the embedded M23 table parses"))
    }

    /// Parses a table file in the format of `m23_atlas_table.g`. `Err` on any missing field,
    /// a class order other than ATLAS order, a list of the wrong length, or a value outside
    /// the four quadratic fields.
    pub fn parse(text: &str) -> Result<AtlasTable, String> {
        let j: serde_json::Value = serde_json::from_str(text).map_err(|e| e.to_string())?;
        let source = j
            .get("source")
            .and_then(|v| v.as_str())
            .ok_or("no source")?
            .to_string();
        let names = j
            .get("class_names")
            .and_then(|v| v.as_array())
            .ok_or("no class_names")?;
        if names.len() != 17 {
            return Err(format!("{} class names", names.len()));
        }
        for (n, c) in names.iter().zip(M23Class::ALL) {
            let n = n.as_str().ok_or("class name is not a string")?;
            if M23Class::from_name(n) != Some(c) {
                return Err(format!("class {n} where {c} is expected (ATLAS order)"));
            }
        }
        let orders = seventeen(unsigned_list::<u32>(&j, "orders")?, "orders")?;
        let centralizer_orders = seventeen(
            unsigned_list::<u64>(&j, "centralizer_orders")?,
            "centralizer_orders",
        )?;
        let class_sizes = seventeen(unsigned_list::<u64>(&j, "class_sizes")?, "class_sizes")?;
        let permutation_character = seventeen(
            int_list(&j, "permutation_character_23")?,
            "permutation_character_23",
        )?;
        let pm = j
            .get("power_maps")
            .and_then(|v| v.as_object())
            .ok_or("no power_maps")?;
        let mut power_maps = Vec::new();
        for (k, v) in pm {
            let k: i64 = k.parse().map_err(|_| format!("power map key {k}"))?;
            let list = v.as_array().ok_or("power map is not a list")?;
            if list.len() != 17 {
                return Err(format!("power map {k}: {} entries", list.len()));
            }
            let mut img = [M23Class::C1A; 17];
            for (o, x) in img.iter_mut().zip(list) {
                let i = x.as_u64().ok_or("power map entry")?;
                *o = usize::try_from(i)
                    .ok()
                    .and_then(|i| i.checked_sub(1))
                    .and_then(M23Class::from_index)
                    .ok_or_else(|| format!("power map {k}: entry {i}"))?;
            }
            power_maps.push((k, img));
        }
        power_maps.sort_by_key(|(k, _)| *k);
        let irr = j
            .get("irreducibles")
            .and_then(|v| v.as_array())
            .ok_or("no irreducibles")?;
        if irr.len() != 17 {
            return Err(format!("{} irreducibles", irr.len()));
        }
        let mut irreducibles = Vec::new();
        for (r, row) in irr.iter().enumerate() {
            let row = row.as_array().ok_or("an irreducible is not a list")?;
            if row.len() != 17 {
                return Err(format!("irreducible {r}: {} values", row.len()));
            }
            let mut vals: Vec<AtlasNumber> = Vec::new();
            for e in row {
                let e = e.as_array().ok_or("a value is not a list")?;
                if e.len() != 3 {
                    return Err("a value is not [x, y, d]".into());
                }
                let x = e[0].as_i64().ok_or("x")?;
                let y = e[1].as_i64().ok_or("y")?;
                let d = e[2].as_u64().ok_or("d")?;
                let d = u32::try_from(d).map_err(|_| format!("d: {d} out of range"))?;
                vals.push(AtlasNumber::from_atlas(x, y, d)?);
            }
            let arr: [AtlasNumber; 17] = vals.try_into().map_err(|_| "17 values")?;
            irreducibles.push(arr);
        }
        Ok(AtlasTable {
            source,
            orders,
            centralizer_orders,
            class_sizes,
            power_maps,
            permutation_character,
            irreducibles,
        })
    }

    /// The `source` field of the file (GAP and CTblLib versions).
    pub fn source(&self) -> &str {
        &self.source
    }

    /// The number of irreducible characters (17).
    pub fn num_irreducibles(&self) -> usize {
        self.irreducibles.len()
    }

    /// `chi_i(c)` for the irreducible `i` (0-based, GAP order; panics for `i >= 17`).
    pub fn value(&self, chi: usize, c: M23Class) -> &AtlasNumber {
        &self.irreducibles[chi][c.index()]
    }

    /// `|C|` from the table.
    pub fn class_size(&self, c: M23Class) -> u64 {
        self.class_sizes[c.index()]
    }

    /// `|C_G(c)|` from the table.
    pub fn centralizer_order(&self, c: M23Class) -> u64 {
        self.centralizer_orders[c.index()]
    }

    /// The element order from the table.
    pub fn element_order(&self, c: M23Class) -> u32 {
        self.orders[c.index()]
    }

    /// The stored power maps `k` (2, 3, 5, 7, 11, 23, -1).
    pub fn power_map_keys(&self) -> Vec<i64> {
        self.power_maps.iter().map(|(k, _)| *k).collect()
    }

    /// The class of `x^k` for `x` in `c`, for a stored `k`; `None` otherwise.
    pub fn power_map(&self, k: i64, c: M23Class) -> Option<M23Class> {
        self.power_maps
            .iter()
            .find(|(j, _)| *j == k)
            .map(|(_, m)| m[c.index()])
    }

    /// The permutation character on the 23 points (the number of fixed points).
    pub fn permutation_character_23(&self, c: M23Class) -> i64 {
        self.permutation_character[c.index()]
    }

    /// Whether every irreducible is rational on `c`.
    pub fn is_rational_class(&self, c: M23Class) -> bool {
        self.irreducibles
            .iter()
            .all(|row| row[c.index()].rational_part().is_some())
    }

    /// The normalized structure constant
    /// `n(C1, C2, C3) = |C1| |C2| |C3| / |G|^2 * sum_chi chi(c1) chi(c2) chi(c3) / chi(1)`,
    /// the number of triples in `C1 x C2 x C3` with product 1, divided by `|G|`. `Err` if the
    /// sum is not rational (impossible for a correct table).
    ///
    /// This is not MAGMA's `StructureConstant(G, i, j, k)`, which is the class-algebra
    /// coefficient `a_{ijk}` (`K_i K_j = sum_k a_{ijk} K_k`). The relation is
    /// `n(C1, C2, C3) = a_{C1, C2, C3^-1} / |C_G(c3)|`; for `(2A, 23A, 23B)`: `a = 161`,
    /// `n = 161 / 23 = 7`.
    pub fn structure_constant(&self, c: [M23Class; 3]) -> Result<Rational, String> {
        let mut s = AtlasNumber::zero();
        for chi in &self.irreducibles {
            let deg = chi[0].rational_part().ok_or("a degree is not rational")?;
            let inv = deg.reciprocal().map_err(|e| format!("{e:?}"))?;
            let term = &(&chi[c[0].index()] * &chi[c[1].index()]) * &chi[c[2].index()];
            s = &s + &term.scale(&inv);
        }
        let s = s
            .rational_part()
            .ok_or("the character sum is not rational")?;
        let g = Rational::from(M23_ORDER as i64);
        let num = Rational::from(self.class_size(c[0]) as i64)
            * Rational::from(self.class_size(c[1]) as i64)
            * Rational::from(self.class_size(c[2]) as i64);
        Ok(num / (g.clone() * g) * s)
    }

    /// Exact row orthogonality `sum_c |c| chi_a(c) conj(chi_b(c)) = |G| delta_ab` and column
    /// orthogonality `sum_chi chi(c) conj(chi(c')) = |C(c)| delta_cc'`; also that the class
    /// sizes sum to `|G|` and `|C| |C(c)| = |G|` (checked arithmetic: an overflow is an `Err`).
    pub fn check_orthogonality(&self) -> Result<(), String> {
        let total = self
            .class_sizes
            .iter()
            .try_fold(0u64, |a, &x| a.checked_add(x));
        if total != Some(M23_ORDER) {
            return Err("the class sizes do not sum to |G|".into());
        }
        for c in M23Class::ALL {
            if self.class_size(c).checked_mul(self.centralizer_order(c)) != Some(M23_ORDER) {
                return Err(format!("|C| |C(c)| != |G| at {c}"));
            }
        }
        let zero = Rational::from(0i64);
        for a in 0..17 {
            for b in 0..17 {
                let mut s = AtlasNumber::zero();
                for c in M23Class::ALL {
                    let t =
                        &self.irreducibles[a][c.index()] * &self.irreducibles[b][c.index()].conj();
                    s = &s + &t.scale(&Rational::from(self.class_size(c) as i64));
                }
                let want = if a == b {
                    Rational::from(M23_ORDER as i64)
                } else {
                    zero.clone()
                };
                if s.rational_part() != Some(want) {
                    return Err(format!("rows {a} and {b} are not orthogonal"));
                }
            }
        }
        for c in M23Class::ALL {
            for d in M23Class::ALL {
                let mut s = AtlasNumber::zero();
                for chi in &self.irreducibles {
                    s = &s + &(&chi[c.index()] * &chi[d.index()].conj());
                }
                let want = if c == d {
                    Rational::from(self.centralizer_order(c) as i64)
                } else {
                    zero.clone()
                };
                if s.rational_part() != Some(want) {
                    return Err(format!("columns {c} and {d} are not orthogonal"));
                }
            }
        }
        Ok(())
    }

    /// Matches the table's columns with RustMath's classes: for every class `c`, the order of
    /// `rep(c)`, the centralizer order computed by `id.centralizer_order` (hence the class
    /// size), the number of fixed points of `rep(c)` against the permutation character, and
    /// for every stored `k` the class of `rep(c)^k` against the power map.
    pub fn check_against(&self, g: &M23, id: &ClassIdentifier) -> Result<(), String> {
        for c in M23Class::ALL {
            let x = id.representative(c);
            if order(&x) != self.element_order(c) || c.element_order() != self.element_order(c) {
                return Err(format!("element order of {c}"));
            }
            let cent = id.centralizer_order(g, c).map_err(|e| e.to_string())?;
            if cent != self.centralizer_order(c) || M23_ORDER / cent != self.class_size(c) {
                return Err(format!("centralizer order of {c}: {cent}"));
            }
            if fixed_mask(&x).count_ones() as i64 != self.permutation_character_23(c) {
                return Err(format!("permutation character at {c}"));
            }
            for (k, m) in &self.power_maps {
                let y = power(&x, *k);
                let got = id.class_of_member(&y).map_err(|e| e.to_string())?;
                if got != m[c.index()] {
                    return Err(format!(
                        "power map {k} at {c}: {got} instead of {}",
                        m[c.index()]
                    ));
                }
            }
        }
        Ok(())
    }

    /// The table as an f64 [`CharacterTable`] (classes named `"1A"` to `"23B"`, characters with
    /// class sizes), for the T-215 inner products.
    pub fn to_float_table(&self) -> CharacterTable {
        let names: Vec<String> = M23Class::ALL.iter().map(|c| c.name().to_string()).collect();
        let sizes: Vec<usize> = M23Class::ALL
            .iter()
            .map(|&c| self.class_size(c) as usize)
            .collect();
        let size_map: HashMap<String, usize> =
            names.iter().cloned().zip(sizes.iter().copied()).collect();
        let chars: Vec<Character> = self
            .irreducibles
            .iter()
            .map(|row| {
                let values: HashMap<String, Complex> = names
                    .iter()
                    .cloned()
                    .zip(row.iter().map(|v| v.to_complex_f64()))
                    .collect();
                let degree = row[0]
                    .rational_part()
                    .and_then(|q| q.to_f64())
                    .map_or(0, |x| x as usize);
                Character::with_class_sizes(degree, values, size_map.clone())
                    .expect("the table has a value and a size on every class")
            })
            .collect();
        CharacterTable::new(M23_ORDER as usize, names, sizes, chars)
            .expect("the class sizes sum to |M23|")
    }
}
