//! M23 and its three-point class vectors (WP-P of the M23 Golay workstream).
//!
//! MAGMA: ch. 58 (permutation groups, conjugacy classes, centralizers), ch. 91 (characters
//! and structure constants), ch. 68 (cohomology), ch. 152 (the Golay code). Digests in
//! `rustmath-lava/docs/`: `Chapter_58_Permutation_Groups.md`,
//! `Chapter_91_Characters_of_Finite_Groups.md`, `Chapter_68_Cohomology_and_Extensions.md`,
//! `Chapter_152_Linear_Codes_over_Finite_Fields.md`.
//!
//! The brief is `docs/workstreams/m23_golay/HANDOFF.md`, Section 4 (WP-P). The reference is the
//! owner's `johnjanik/M23` at `2d11038` (`scripts/passports_all.py` and the `m23golay`
//! modules), whose algorithms are ported here; its data files are the test references
//! (`tests/data/m23/`, with a README).
//!
//! Modules:
//! - [`group`]: M23 on the published generators of HJLPPZ (arXiv:2608.08538v2, 3.1), its
//!   elements from the stabilizer chain, the Steiner system S(4,7,23), the even Golay code.
//! - [`classes`]: the 17 classes, with the split pairs identified exactly; class sizes and
//!   centralizer orders.
//! - [`atlas`]: the ATLAS character table of M23 as data (generated by GAP), in exact
//!   arithmetic; structure constants.
//! - [`three_point`]: the 57 class vectors, the counting of Nielsen classes, generation by
//!   transitivity, real points, genus.
//! - [`nielsen`]: the Nielsen classes `(C, 23A, 23B)`, complex conjugation, real structures,
//!   ovals.
//! - [`cohomology`]: parabolic cohomology over `F_2` of the Golay modules `G0`, `P0 / G0`, `P0`.
//!
//! Conventions (HANDOFF Section 1): permutations act on the right, `x^(gh) = (x^g)^h`; a
//! product is read left to right; a [`Perm23`] is a 0-based image list; published cycles are
//! 1-based. Class names inside a split pair are a convention, fixed in [`classes`].
//!
//! The code uses no `unsafe`.

