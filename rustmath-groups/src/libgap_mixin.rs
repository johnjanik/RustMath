//! LibGAP Mixin - Additional group properties and methods
//!
//! This module provides a mixin trait that adds extensive group-theoretic
//! functionality to groups. In SageMath, this provides access to GAP methods.
//! Here we provide pure Rust implementations.
//!
//! MAGMA reference: Handbook ch. 57 (Groups), intrinsics `IsAbelian`, `IsCyclic`,
//! `IsNilpotent`, `IsSoluble`, `IsSimple`, `IsPerfect`, `IsSupersoluble`,
//! `IsPolycyclic`, `IsPGroup`, `Exponent`, `DerivedSubgroup`, `NormalSubgroups`
//! (digest: `rustmath-lava/docs/Chapter_57_Groups.md`). The algorithms here are
//! the textbook definitions applied to the full element list returned by
//! [`FiniteGroupTrait::elements`] (lower central / derived series, normal
//! closures, chief series; see D. J. S. Robinson, *A Course in the Theory of
//! Groups*, ch. 5), so they cost O(|G|²) group operations or more and are meant
//! for small groups only.
//!
//! All identities are taken from the parent ([`Group::identity`]), never from the
//! context-free [`GroupElement::identity`], which cannot know e.g. the modulus or
//! degree of a runtime-parameterised element type.
//!
//! # Overview
//!
//! The `GroupMixinLibGAP` trait provides methods for:
//! - Testing group properties (abelian, nilpotent, solvable, simple, perfect)
//! - Computing conjugacy classes and character tables
//! - Finding subgroups, centralizers, normalizers
//! - Analyzing group structure
//!
//! # Example
//!
//! ```
//! use rustmath_groups::libgap_mixin::GroupMixinLibGAP;
//! ```

use std::collections::{HashMap, HashSet};
use crate::group_traits::{Group, GroupElement, FiniteGroupTrait};

/// Mixin trait providing LibGAP-style group methods
///
/// This trait extends basic group functionality with advanced
/// group-theoretic operations and property tests.
///
/// Every method works on the full element list [`FiniteGroupTrait::elements`] and
/// assumes it is a group with identity [`Group::identity`]. If it is not (an
/// element whose order exceeds the list length, or a generated subgroup larger
/// than the list), the methods panic rather than return a fabricated answer.
pub trait GroupMixinLibGAP: Group + FiniteGroupTrait {
    /// Test if the group is abelian (commutative)
    ///
    /// A group G is abelian if gh = hg for all g, h in G. Checked exactly over
    /// all pairs of elements.
    fn is_abelian_libgap(&self) -> bool {
        let elements = self.elements();
        for (i, g) in elements.iter().enumerate() {
            for h in &elements[i + 1..] {
                if g.op(h) != h.op(g) {
                    return false;
                }
            }
        }
        true
    }

    /// Test if the group is cyclic
    ///
    /// A finite group is cyclic iff some element has order |G|.
    fn is_cyclic(&self) -> bool {
        let elements = self.elements();
        let n = elements.len();
        let id = self.identity();
        elements
            .iter()
            .any(|g| element_order_in(g, &id, n) == n)
    }

    /// Test if the group is nilpotent
    ///
    /// A group is nilpotent if its lower central series
    /// γ₁ = G, γᵢ₊₁ = [G, γᵢ] reaches the trivial group.
    fn is_nilpotent(&self) -> bool {
        let elements = self.elements();
        let n = elements.len();
        let id = self.identity();

        let mut current = elements.clone();
        loop {
            if current.len() == 1 {
                return true;
            }
            let commutators: HashSet<Self::Element> = elements
                .iter()
                .flat_map(|g| current.iter().map(move |h| g.commutator(h)))
                .collect();
            let gens: Vec<Self::Element> = commutators.into_iter().collect();
            let next = subgroup_in(&id, &gens, n);
            // γᵢ₊₁ ⊆ γᵢ, so equal sizes mean the series has stabilised above 1.
            if next.len() == current.len() {
                return false;
            }
            current = next;
        }
    }

    /// Test if the group is solvable
    ///
    /// A group is solvable if its derived series
    /// G⁽⁰⁾ = G, G⁽ⁱ⁺¹⁾ = [G⁽ⁱ⁾, G⁽ⁱ⁾] reaches the trivial group.
    fn is_solvable(&self) -> bool {
        let elements = self.elements();
        let n = elements.len();
        let id = self.identity();

        let mut current = elements;
        loop {
            if current.len() == 1 {
                return true;
            }
            let next = derived_subgroup_of(&current, &id, n);
            // G⁽ⁱ⁺¹⁾ ⊆ G⁽ⁱ⁾, so equal sizes mean the series has stabilised above 1.
            if next.len() == current.len() {
                return false;
            }
            current = next;
        }
    }

    /// Test if the group is simple
    ///
    /// A group is simple if it is nontrivial and has no normal subgroups other
    /// than 1 and itself. Equivalently, the normal closure of every nontrivial
    /// element (the subgroup generated by its conjugacy class) is the whole
    /// group. The trivial group is not simple.
    fn is_simple(&self) -> bool {
        let order = self.finite_order();
        if order == 1 {
            return false;
        }
        let id = self.identity();
        self.conjugacy_classes()
            .iter()
            .filter(|class| !class.contains(&id))
            .all(|class| subgroup_in(&id, class, order).len() == order)
    }

    /// Test if the group is perfect
    ///
    /// A group is perfect if it equals its commutator subgroup.
    fn is_perfect(&self) -> bool {
        self.derived_subgroup().len() == self.finite_order()
    }

    /// Test if the group is supersolvable
    ///
    /// A finite group is supersolvable iff every chief factor has prime order.
    /// A chief series is built greedily from [`normal_subgroups`](Self::normal_subgroups):
    /// above the current term N the smallest normal subgroup strictly containing
    /// N is a minimal normal subgroup over N.
    fn is_supersolvable(&self) -> bool {
        let normals: Vec<HashSet<Self::Element>> = self
            .normal_subgroups()
            .into_iter()
            .map(|n| n.into_iter().collect())
            .collect();
        let order = self.finite_order();

        // normal_subgroups is sorted by size, trivial subgroup first.
        let mut current = &normals[0];
        while current.len() < order {
            let next = normals
                .iter()
                .filter(|m| m.len() > current.len() && current.is_subset(m))
                .min_by_key(|m| m.len())
                .expect("the whole group is a normal subgroup containing every term");
            if !is_prime(next.len() / current.len()) {
                return false;
            }
            current = next;
        }
        true
    }

    /// Test if the group is polycyclic
    ///
    /// A group is polycyclic if it has a subnormal series with cyclic factors.
    /// For finite groups this is equivalent to solvability.
    fn is_polycyclic(&self) -> bool {
        self.is_solvable()
    }

    /// Test if the group is a p-group
    ///
    /// A group is a p-group if p is prime and its order is a power of p
    /// (the trivial group is a p-group for every prime p). Returns `false`
    /// when `p` is not prime.
    fn is_p_group(&self, p: usize) -> bool {
        if !is_prime(p) {
            return false;
        }

        let mut order = self.finite_order();
        while order > 1 {
            if order % p != 0 {
                return false;
            }
            order /= p;
        }

        true
    }

    /// Get the cardinality (order) of the group
    fn cardinality(&self) -> usize {
        self.finite_order()
    }

    /// Get all elements as a list (alias for elements)
    fn list(&self) -> Vec<Self::Element> {
        self.elements()
    }

    /// Generate a random element from the group
    fn random_element_libgap(&self) -> Self::Element {
        let elements = self.elements();
        if elements.is_empty() {
            return self.identity();
        }

        use std::collections::hash_map::RandomState;
        use std::hash::{BuildHasher, Hash, Hasher};

        let s = RandomState::new();
        let mut hasher = s.build_hasher();
        std::time::SystemTime::now().hash(&mut hasher);
        let idx = (hasher.finish() as usize) % elements.len();

        elements[idx].clone()
    }

    /// Compute the exponent of the group
    ///
    /// The exponent is the LCM of all element orders. Element orders are
    /// computed against the group's identity [`Group::identity`] and are
    /// bounded by |G| (Lagrange).
    fn exponent_libgap(&self) -> usize {
        let elements = self.elements();
        let n = elements.len();
        let id = self.identity();

        elements
            .iter()
            .map(|g| element_order_in(g, &id, n))
            .fold(1, lcm)
    }

    /// All normal subgroups of the group, each listed with the identity first,
    /// sorted by size (the trivial subgroup first, the whole group last).
    ///
    /// Every normal subgroup N is the join of the normal closures of the
    /// conjugacy classes it contains, so the list is the closure of {1} under
    /// joins with the normal closures of the conjugacy classes. The join of two
    /// normal subgroups N, M is the product set NM. Cost grows with the number
    /// of normal subgroups (times the number of classes times |G|²).
    fn normal_subgroups(&self) -> Vec<Vec<Self::Element>> {
        let elements = self.elements();
        let n = elements.len();
        let id = self.identity();
        let index: HashMap<Self::Element, usize> = elements
            .iter()
            .cloned()
            .enumerate()
            .map(|(i, g)| (g, i))
            .collect();
        let idx = |g: &Self::Element| -> usize {
            *index
                .get(g)
                .expect("product of group elements is not in elements(): not a group")
        };

        let to_key = |sub: &[Self::Element]| -> Vec<usize> {
            let mut key: Vec<usize> = sub.iter().map(&idx).collect();
            key.sort_unstable();
            key
        };

        let trivial = vec![idx(&id)];
        let mut subgroups: Vec<Vec<usize>> = vec![trivial.clone()];
        let mut seen: HashSet<Vec<usize>> = HashSet::from([trivial]);

        for class in self.conjugacy_classes() {
            if class.contains(&id) {
                continue;
            }
            let closure = to_key(&subgroup_in(&id, &class, n));
            if seen.contains(&closure) {
                // Already a join of earlier closures, so all its joins are present.
                continue;
            }
            let snapshot = subgroups.clone();
            for sub in &snapshot {
                let mut product: Vec<usize> = sub
                    .iter()
                    .flat_map(|&a| closure.iter().map(move |&b| (a, b)))
                    .map(|(a, b)| idx(&elements[a].op(&elements[b])))
                    .collect::<HashSet<usize>>()
                    .into_iter()
                    .collect();
                product.sort_unstable();
                if seen.insert(product.clone()) {
                    subgroups.push(product);
                }
            }
        }

        subgroups.sort_by_key(|s| s.len());
        let id_index = idx(&id);
        subgroups
            .into_iter()
            .map(|sub| {
                let mut out = vec![elements[id_index].clone()];
                out.extend(
                    sub.into_iter()
                        .filter(|&i| i != id_index)
                        .map(|i| elements[i].clone()),
                );
                out
            })
            .collect()
    }

    /// Check whether the group has a normal subgroup of the given order
    /// (the trivial subgroup and the whole group included).
    fn has_normal_subgroup_of_size(&self, size: usize) -> bool {
        self.normal_subgroups().iter().any(|sub| sub.len() == size)
    }

    /// Compute the derived subgroup (commutator subgroup)
    ///
    /// The derived subgroup is generated by all commutators [g, h] = ghg⁻¹h⁻¹
    /// (the set of commutators itself need not be a subgroup, so its closure is
    /// taken). The identity is listed first.
    fn derived_subgroup(&self) -> Vec<Self::Element> {
        let elements = self.elements();
        let n = elements.len();
        derived_subgroup_of(&elements, &self.identity(), n)
    }

    /// Compute the commutator subgroup (alias for derived_subgroup)
    fn commutator_subgroup(&self) -> Vec<Self::Element> {
        self.derived_subgroup()
    }

    /// Get the trivial character (all values = 1)
    fn trivial_character(&self) -> Vec<f64> {
        let n = self.conjugacy_classes().len();
        vec![1.0; n]
    }
}

/// Order of `g` in a finite group of order `group_order` with identity
/// `identity`: the least k ≥ 1 with gᵏ = identity.
///
/// # Panics
///
/// If gᵏ ≠ identity for every k ≤ `group_order`, which by Lagrange's theorem
/// means `g`, `identity` and `group_order` do not describe a finite group.
pub(crate) fn element_order_in<E: GroupElement>(g: &E, identity: &E, group_order: usize) -> usize {
    let mut current = g.clone();
    let mut k = 1;
    while current != *identity {
        if k >= group_order {
            panic!(
                "element {} has no power equal to the identity {} up to the group order {}: \
                 the element list is not a group",
                g, identity, group_order
            );
        }
        current = current.op(g);
        k += 1;
    }
    k
}

/// The subgroup generated by `gens` inside a finite group: the closure of
/// `{identity}` under right multiplication by `gens` (in a finite group every
/// inverse is a positive power). The identity is listed first, the rest in
/// breadth-first order.
///
/// Returns `None` as soon as the closure has more than `bound` elements.
pub(crate) fn generated_subgroup<E: GroupElement>(
    identity: &E,
    gens: &[E],
    bound: usize,
) -> Option<Vec<E>> {
    let mut elements = vec![identity.clone()];
    let mut seen: HashSet<E> = HashSet::from([identity.clone()]);
    let mut next = 0;
    while next < elements.len() {
        let current = elements[next].clone();
        next += 1;
        for gen in gens {
            let new_elem = current.op(gen);
            if seen.insert(new_elem.clone()) {
                elements.push(new_elem);
                if elements.len() > bound {
                    return None;
                }
            }
        }
    }
    Some(elements)
}

/// [`generated_subgroup`] inside the group whose element list has length
/// `group_order`.
///
/// # Panics
///
/// If the closure is larger than the group (the element list is then not a
/// group).
fn subgroup_in<E: GroupElement>(identity: &E, gens: &[E], group_order: usize) -> Vec<E> {
    generated_subgroup(identity, gens, group_order).unwrap_or_else(|| {
        panic!(
            "subgroup generated by {} element(s) exceeds the group order {}: \
             the element list is not a group",
            gens.len(),
            group_order
        )
    })
}

/// The derived subgroup [H, H] of the finite subgroup `h` (listed as all of its
/// elements) of a group of order at most `bound`.
fn derived_subgroup_of<E: GroupElement>(h: &[E], identity: &E, bound: usize) -> Vec<E> {
    let commutators: HashSet<E> = h
        .iter()
        .flat_map(|a| h.iter().map(move |b| a.commutator(b)))
        .collect();
    let gens: Vec<E> = commutators.into_iter().collect();
    subgroup_in(identity, &gens, bound)
}

/// Trial-division primality test for small integers.
fn is_prime(n: usize) -> bool {
    if n < 2 {
        return false;
    }
    let mut d = 2;
    while d * d <= n {
        if n % d == 0 {
            return false;
        }
        d += 1;
    }
    true
}

/// Compute the least common multiple of two numbers
pub(crate) fn lcm(a: usize, b: usize) -> usize {
    if a == 0 || b == 0 {
        return 0;
    }
    (a / gcd(a, b)) * b
}

/// Compute the greatest common divisor of two numbers
fn gcd(mut a: usize, mut b: usize) -> usize {
    while b != 0 {
        let temp = b;
        b = a % b;
        a = temp;
    }
    a
}

