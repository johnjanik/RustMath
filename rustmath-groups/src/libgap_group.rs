//! LibGAP Group - Generic group interface
//!
//! This module provides a generic group interface for groups in RustMath.
//! In SageMath, GroupLibGAP provides an interface to GAP-based groups.
//! Here we provide a pure Rust implementation with similar functionality.
//!
//! MAGMA reference: Handbook ch. 57 (Groups), `Order`, `Exponent`, `in`,
//! `Random`, `Classes`, `Centre` (digest: `rustmath-lava/docs/Chapter_57_Groups.md`).
//! This generic type only knows its generators and a declared order, so every
//! element-level computation goes through an explicit enumeration of the group
//! (closure of the generators), which is limited to [`ENUMERATION_LIMIT`]
//! elements. Beyond that (or for an infinite / unknown order) the methods say
//! so (`None`, or a panic where the signature cannot express it) instead of
//! guessing; Schreier–Sims or coset enumeration is not implemented here.
//!
//! # Overview
//!
//! The main class `GroupLibGAP` represents a group with generators and
//! provides methods for group operations, properties, and computations.
//!
//! # Example
//!
//! ```
//! use rustmath_groups::libgap_group::GroupLibGAP;
//! ```

use std::fmt;
use crate::group_traits::{Group, GroupElement, FiniteGroupTrait};
use crate::libgap_mixin::{element_order_in, generated_subgroup, lcm};
use crate::libgap_wrapper::{ElementLibGAP, ParentLibGAP};

/// Largest declared order for which [`GroupLibGAP`] enumerates its elements.
pub const ENUMERATION_LIMIT: usize = 10_000;

/// Generic group structure using LibGAP-style interface
///
/// This struct represents a group defined by generators and relations.
/// It provides a generic interface for working with various types of groups.
///
/// The declared `order` and `is_abelian` are taken on trust by
/// [`Group::order`] and [`Group::is_abelian`]; the order is checked against the
/// generators whenever the group is enumerated.
///
/// # Type Parameters
///
/// - `E`: The element type, which must implement `GroupElement` and `ElementLibGAP`
#[derive(Clone, Debug)]
pub struct GroupLibGAP<E: GroupElement + ElementLibGAP> {
    /// Generators of the group
    generators: Vec<E>,

    /// Order of the group (None if infinite)
    order: Option<usize>,

    /// Whether the group is abelian
    is_abelian: bool,

    /// Description of the group
    description: String,

    /// Cached elements (for finite groups)
    cached_elements: Option<Vec<E>>,
}

impl<E: GroupElement + ElementLibGAP> GroupLibGAP<E> {
    /// Create a new group from generators
    ///
    /// # Arguments
    ///
    /// - `generators`: List of group generators
    /// - `order`: Order of the group (None for infinite groups)
    /// - `is_abelian`: Whether the group is abelian
    ///
    /// # Example
    ///
    /// ```ignore
    /// let g = GroupLibGAP::new(vec![gen1, gen2], Some(12), false);
    /// ```
    pub fn new(generators: Vec<E>, order: Option<usize>, is_abelian: bool) -> Self {
        GroupLibGAP {
            description: format!("Group with {} generators", generators.len()),
            generators,
            order,
            is_abelian,
            cached_elements: None,
        }
    }

    /// Create a new group with a custom description
    pub fn with_description(
        generators: Vec<E>,
        order: Option<usize>,
        is_abelian: bool,
        description: String,
    ) -> Self {
        GroupLibGAP {
            generators,
            order,
            is_abelian,
            description,
            cached_elements: None,
        }
    }

    /// Create a trivial group (containing only the identity)
    pub fn trivial() -> Self {
        GroupLibGAP {
            generators: vec![],
            order: Some(1),
            is_abelian: true,
            description: "Trivial group".to_string(),
            cached_elements: Some(vec![E::identity()]),
        }
    }

    /// Create a cyclic group of order n generated by `generator`
    ///
    /// `order` must be the order of `generator`; it is checked when the group
    /// is enumerated.
    pub fn cyclic(generator: E, order: usize) -> Self {
        GroupLibGAP {
            generators: vec![generator],
            order: Some(order),
            is_abelian: true,
            description: format!("Cyclic group of order {}", order),
            cached_elements: None,
        }
    }

    /// Get the generators of this group
    pub fn gens(&self) -> &[E] {
        &self.generators
    }

    /// Get the number of generators
    pub fn ngens(&self) -> usize {
        self.generators.len()
    }

    /// Get the i-th generator (0-indexed)
    pub fn gen(&self, i: usize) -> Option<&E> {
        self.generators.get(i)
    }

    /// Check if this group is abelian
    pub fn is_abelian_group(&self) -> bool {
        self.is_abelian
    }

    /// The identity of this group.
    ///
    /// Computed as `g · g⁻¹` for the first generator `g`, so it is the identity
    /// of the group the generators live in even when the element type's
    /// context-free [`GroupElement::identity`] cannot know that group (residues
    /// modulo a runtime modulus, permutations of a runtime degree, ...). A group
    /// without generators falls back to `E::identity()`.
    fn group_identity(&self) -> E {
        match self.generators.first() {
            Some(g) => g.op(&g.inverse()),
            None => E::identity(),
        }
    }

    /// Enumerate the elements as the closure of the identity under right
    /// multiplication by the generators (in a finite group every inverse is a
    /// positive power, so this is the whole group). The identity comes first,
    /// then breadth-first order.
    ///
    /// Returns `None` when the order is unknown/infinite or exceeds
    /// [`ENUMERATION_LIMIT`].
    ///
    /// # Panics
    ///
    /// If the generators do not generate a group of the declared order.
    fn enumerate(&self) -> Option<Vec<E>> {
        let order = self.order?;
        if order > ENUMERATION_LIMIT {
            return None;
        }
        match generated_subgroup(&self.group_identity(), &self.generators, order) {
            Some(elements) if elements.len() == order => Some(elements),
            Some(elements) => panic!(
                "GroupLibGAP: the generators generate a group of order {}, not the declared order {}",
                elements.len(),
                order
            ),
            None => panic!(
                "GroupLibGAP: the generators generate more than the declared order {} elements",
                order
            ),
        }
    }

    /// The cached elements, or a fresh enumeration (`None` when the group
    /// cannot be enumerated, see [`compute_elements`](Self::compute_elements)).
    fn element_list(&self) -> Option<Vec<E>> {
        match self.cached_elements {
            Some(ref elements) => Some(elements.clone()),
            None => self.enumerate(),
        }
    }

    /// Compute (and cache) the elements of the group (for finite groups)
    ///
    /// This enumerates all elements by taking products of generators.
    /// Returns `None` when the declared order is `None` (infinite or unknown)
    /// or larger than [`ENUMERATION_LIMIT`].
    ///
    /// # Panics
    ///
    /// If the generators do not generate a group of the declared order.
    pub fn compute_elements(&mut self) -> Option<&[E]> {
        if self.cached_elements.is_none() {
            self.cached_elements = Some(self.enumerate()?);
        }
        self.cached_elements.as_deref()
    }

    /// Get an element by index (for finite groups with cached elements)
    pub fn element_at(&self, index: usize) -> Option<&E> {
        self.cached_elements.as_ref()?.get(index)
    }

    /// Decide whether an element is in the group.
    ///
    /// Uses the cached elements, or enumerates the group. Returns `None`
    /// (undecided) when the group cannot be enumerated: its order is unknown,
    /// infinite, or larger than [`ENUMERATION_LIMIT`].
    pub fn try_contains(&self, element: &E) -> Option<bool> {
        if let Some(ref elements) = self.cached_elements {
            return Some(elements.contains(element));
        }
        self.enumerate().map(|elements| elements.contains(element))
    }

    /// Check if an element is in the group
    ///
    /// For finite groups with cached elements, this checks membership directly;
    /// otherwise the group is enumerated.
    ///
    /// # Panics
    ///
    /// When membership cannot be decided (see [`try_contains`](Self::try_contains)):
    /// that needs Schreier–Sims or coset enumeration, which is not implemented
    /// for this generic type.
    pub fn contains(&self, element: &E) -> bool {
        self.try_contains(element).unwrap_or_else(|| {
            unimplemented!(
                "GroupLibGAP::contains: membership needs a declared finite order <= {} \
                 (Schreier-Sims / coset enumeration not implemented)",
                ENUMERATION_LIMIT
            )
        })
    }

    /// Generate a random element (for finite groups)
    ///
    /// Returns `None` when the group cannot be enumerated (order unknown,
    /// infinite, or larger than [`ENUMERATION_LIMIT`]).
    pub fn random_element(&self) -> Option<E> {
        use std::collections::hash_map::RandomState;
        use std::hash::{BuildHasher, Hash, Hasher};

        let pick = |elements: &[E]| -> E {
            let s = RandomState::new();
            let mut hasher = s.build_hasher();
            std::time::SystemTime::now().hash(&mut hasher);
            let idx = (hasher.finish() as usize) % elements.len();
            elements[idx].clone()
        };

        match self.cached_elements {
            Some(ref elements) => Some(pick(elements)),
            None => self.enumerate().map(|elements| pick(&elements)),
        }
    }

    /// Get the description of this group
    pub fn description(&self) -> &str {
        &self.description
    }

    /// Set the description of this group
    pub fn set_description(&mut self, description: String) {
        self.description = description;
    }
}

impl<E: GroupElement + ElementLibGAP> fmt::Display for GroupLibGAP<E> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.description)
    }
}

impl<E: GroupElement + ElementLibGAP> Group for GroupLibGAP<E> {
    type Element = E;

    fn identity(&self) -> Self::Element {
        self.group_identity()
    }

    fn is_abelian(&self) -> bool {
        self.is_abelian
    }

    fn is_finite(&self) -> bool {
        self.order.is_some()
    }

    fn order(&self) -> Option<usize> {
        self.order
    }

    fn contains(&self, element: &Self::Element) -> bool {
        self.contains(element)
    }

    /// The LCM of the element orders.
    ///
    /// Returns `None` if the group was declared infinite (`order` is `None`).
    ///
    /// # Panics
    ///
    /// For a finite group larger than [`ENUMERATION_LIMIT`]: computing its
    /// exponent needs a structural algorithm that is not implemented here.
    fn exponent(&self) -> Option<usize> {
        self.order?;
        let elements = self.element_list().unwrap_or_else(|| {
            unimplemented!(
                "GroupLibGAP::exponent: groups of order > {} cannot be enumerated",
                ENUMERATION_LIMIT
            )
        });
        let id = self.group_identity();
        let n = elements.len();
        Some(
            elements
                .iter()
                .map(|g| element_order_in(g, &id, n))
                .fold(1, lcm),
        )
    }
}

impl<E: GroupElement + ElementLibGAP> ParentLibGAP for GroupLibGAP<E> {
    type Element = E;

    fn identity_element(&self) -> Self::Element {
        self.group_identity()
    }

    fn generators(&self) -> Vec<Self::Element> {
        self.generators.clone()
    }

    fn contains_element(&self, element: &Self::Element) -> bool {
        self.contains(element)
    }

    fn group_order(&self) -> Option<usize> {
        self.order
    }

    fn random_element(&self) -> Option<Self::Element> {
        self.random_element()
    }

    /// The elements (cached or freshly enumerated); `None` when the group
    /// cannot be enumerated.
    fn all_elements(&self) -> Option<Vec<Self::Element>> {
        self.element_list()
    }
}

/// `conjugacy_classes` and `center` use the [`FiniteGroupTrait`] defaults, which
/// work on [`elements`](FiniteGroupTrait::elements).
impl<E: GroupElement + ElementLibGAP> FiniteGroupTrait for GroupLibGAP<E> {
    /// All elements (cached, or enumerated on the fly).
    ///
    /// # Panics
    ///
    /// When the group cannot be enumerated (order unknown, infinite, or larger
    /// than [`ENUMERATION_LIMIT`]).
    fn elements(&self) -> Vec<Self::Element> {
        self.element_list().unwrap_or_else(|| {
            unimplemented!(
                "GroupLibGAP::elements: enumeration needs a declared finite order <= {}",
                ENUMERATION_LIMIT
            )
        })
    }

    /// # Panics
    ///
    /// If the group was not declared finite.
    fn finite_order(&self) -> usize {
        self.order
            .unwrap_or_else(|| panic!("GroupLibGAP::finite_order: the group is not declared finite"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::cmp::Ordering;

    // Test element type: residues modulo a runtime modulus. Like other
    // runtime-parameterised element types (permutations of a runtime degree),
    // its context-free `identity()` cannot know the modulus and returns the
    // modulus-1 zero, so these tests also check that GroupLibGAP takes its
    // identity from its generators rather than from `E::identity()`.
    #[derive(Clone, Debug, PartialEq, Eq, Hash)]
    struct ModInt {
        value: i64,
        modulus: i64,
    }

    impl ModInt {
        fn new(value: i64, modulus: i64) -> Self {
            ModInt {
                value: value.rem_euclid(modulus),
                modulus,
            }
        }
    }

    impl fmt::Display for ModInt {
        fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
            write!(f, "{} mod {}", self.value, self.modulus)
        }
    }

    impl PartialOrd for ModInt {
        fn partial_cmp(&self, other: &Self) -> Option<Ordering> {
            Some(self.value.cmp(&other.value))
        }
    }

    impl Ord for ModInt {
        fn cmp(&self, other: &Self) -> Ordering {
            self.value.cmp(&other.value)
        }
    }

    impl GroupElement for ModInt {
        fn identity() -> Self {
            ModInt::new(0, 1)
        }

        fn inverse(&self) -> Self {
            ModInt::new(-self.value, self.modulus)
        }

        fn op(&self, other: &Self) -> Self {
            ModInt::new(self.value + other.value, self.modulus)
        }
    }

    impl ElementLibGAP for ModInt {}

    #[test]
    fn test_trivial_group() {
        let g: GroupLibGAP<ModInt> = GroupLibGAP::trivial();
        assert!(g.is_abelian());
        assert!(g.is_finite());
        assert_eq!(g.order(), Some(1));
        assert_eq!(g.ngens(), 0);
    }

    #[test]
    fn test_cyclic_group() {
        let gen = ModInt::new(1, 5);
        let g = GroupLibGAP::cyclic(gen, 5);
        assert!(g.is_abelian());
        assert_eq!(g.order(), Some(5));
        assert_eq!(g.ngens(), 1);
    }

    #[test]
    fn test_group_generators() {
        let gen1 = ModInt::new(1, 10);
        let gen2 = ModInt::new(2, 10);
        let g = GroupLibGAP::new(vec![gen1.clone(), gen2.clone()], Some(10), true);

        assert_eq!(g.ngens(), 2);
        assert_eq!(g.gen(0), Some(&gen1));
        assert_eq!(g.gen(1), Some(&gen2));
        assert_eq!(g.gen(2), None);
    }

    #[test]
    fn test_group_identity() {
        let gen = ModInt::new(1, 7);
        let g = GroupLibGAP::cyclic(gen, 7);
        let id = g.identity();
        assert_eq!(id.value, 0);
        assert_eq!(id, ModInt::new(0, 7));
        assert_eq!(id.op(&ModInt::new(3, 7)), ModInt::new(3, 7));
    }

    #[test]
    fn test_compute_elements() {
        let gen = ModInt::new(1, 5);
        let mut g = GroupLibGAP::cyclic(gen, 5);

        let elements = g.compute_elements();
        assert!(elements.is_some());
        assert_eq!(elements.unwrap().len(), 5);
    }

    #[test]
    fn test_group_display() {
        let gen = ModInt::new(1, 3);
        let g = GroupLibGAP::cyclic(gen, 3);
        let display = format!("{}", g);
        assert!(display.contains("Cyclic group"));
    }

    #[test]
    fn test_group_with_description() {
        let gen = ModInt::new(1, 4);
        let g = GroupLibGAP::with_description(
            vec![gen],
            Some(4),
            true,
            "Test group Z/4Z".to_string()
        );
        assert_eq!(g.description(), "Test group Z/4Z");
    }

    #[test]
    fn test_parent_libgap_interface() {
        let gen = ModInt::new(1, 6);
        let g = GroupLibGAP::cyclic(gen.clone(), 6);

        assert_eq!(g.identity_element().value, 0);
        assert_eq!(g.group_order(), Some(6));
        assert!(g.is_finite_group());

        let gens = g.generators();
        assert_eq!(gens.len(), 1);
        assert_eq!(gens[0], gen);
    }

    #[test]
    fn test_finite_group_trait() {
        let gen = ModInt::new(1, 4);
        let mut g = GroupLibGAP::cyclic(gen, 4);
        g.compute_elements();

        assert_eq!(g.finite_order(), 4);
        let elems = g.elements();
        assert_eq!(elems.len(), 4);
    }

    #[test]
    fn test_conjugacy_classes_abelian() {
        let gen = ModInt::new(1, 3);
        let mut g = GroupLibGAP::cyclic(gen, 3);
        g.compute_elements();

        let classes = g.conjugacy_classes();
        // In an abelian group, each element is its own conjugacy class
        assert_eq!(classes.len(), 3);
        for class in classes {
            assert_eq!(class.len(), 1);
        }
    }

    #[test]
    fn test_center_abelian() {
        let gen = ModInt::new(1, 4);
        let mut g = GroupLibGAP::cyclic(gen, 4);
        g.compute_elements();

        let center = g.center();
        // In an abelian group, the center is the whole group
        assert_eq!(center.len(), 4);
    }

    #[test]
    fn test_element_at() {
        let gen = ModInt::new(1, 3);
        let mut g = GroupLibGAP::cyclic(gen, 3);
        g.compute_elements();

        assert!(g.element_at(0).is_some());
        assert!(g.element_at(2).is_some());
        assert!(g.element_at(3).is_none());
    }

    #[test]
    fn test_contains() {
        let gen = ModInt::new(1, 5);
        let mut g = GroupLibGAP::cyclic(gen, 5);
        g.compute_elements();

        let elem = ModInt::new(2, 5);
        assert!(g.contains(&elem));

        let elem_outside = ModInt::new(2, 7);
        assert!(!g.contains(&elem_outside));
    }

    #[test]
    fn test_contains_enumerates_without_cache() {
        let g = GroupLibGAP::cyclic(ModInt::new(1, 5), 5);
        assert!(g.element_at(0).is_none()); // nothing cached
        assert!(g.contains(&ModInt::new(2, 5)));
        assert!(!g.contains(&ModInt::new(2, 7)));
        assert_eq!(g.try_contains(&ModInt::new(4, 5)), Some(true));

        // Proper subgroup 2Z/10Z of Z/10Z: an element of the same type outside it.
        let h = GroupLibGAP::cyclic(ModInt::new(2, 10), 5);
        assert!(h.contains(&ModInt::new(4, 10)));
        assert!(!h.contains(&ModInt::new(3, 10)));
    }

    #[test]
    fn test_membership_undecided_for_infinite_group() {
        // Declared infinite: membership cannot be decided by enumeration.
        let g = GroupLibGAP::new(vec![ModInt::new(1, 5)], None, true);
        assert_eq!(g.try_contains(&ModInt::new(2, 5)), None);
        assert_eq!(g.random_element(), None);
        assert_eq!(g.all_elements(), None);
        assert_eq!(g.exponent(), None);
    }

    #[test]
    #[should_panic(expected = "membership")]
    fn test_contains_panics_when_undecidable() {
        let g = GroupLibGAP::new(vec![ModInt::new(1, 5)], None, true);
        g.contains(&ModInt::new(2, 5));
    }

    #[test]
    #[should_panic(expected = "not declared finite")]
    fn test_finite_order_panics_for_infinite_group() {
        let g = GroupLibGAP::new(vec![ModInt::new(1, 5)], None, true);
        g.finite_order();
    }

    #[test]
    #[should_panic(expected = "declared order")]
    fn test_declared_order_mismatch_panics() {
        // 1 generates Z/5Z, which does not have order 4.
        let mut g = GroupLibGAP::cyclic(ModInt::new(1, 5), 4);
        g.compute_elements();
    }

    #[test]
    fn test_elements_without_cache() {
        let g = GroupLibGAP::cyclic(ModInt::new(1, 6), 6);
        let elems = g.elements();
        assert_eq!(elems.len(), 6);
        let set: std::collections::HashSet<_> = elems.iter().cloned().collect();
        assert_eq!(set.len(), 6);
        assert_eq!(elems[0], ModInt::new(0, 6));
        assert_eq!(g.all_elements().map(|e| e.len()), Some(6));
        assert_eq!(g.center().len(), 6);
        assert_eq!(g.conjugacy_classes().len(), 6);
    }

    #[test]
    fn test_exponent() {
        // Exponent(CyclicGroup(6)) = 6; the subgroup 2Z/12Z has order 6, exponent 6.
        assert_eq!(GroupLibGAP::cyclic(ModInt::new(1, 6), 6).exponent(), Some(6));
        assert_eq!(GroupLibGAP::cyclic(ModInt::new(2, 12), 6).exponent(), Some(6));
        assert_eq!(GroupLibGAP::<ModInt>::trivial().exponent(), Some(1));
    }

    #[test]
    fn test_random_element_is_member() {
        let g = GroupLibGAP::cyclic(ModInt::new(3, 9), 3);
        for _ in 0..10 {
            let r = g.random_element().unwrap();
            assert!(g.contains(&r));
        }
    }

    // Permutations of {0, 1, 2} (degree fixed by the type), GAP's
    // left-to-right composition.
    #[derive(Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
    struct Perm3([usize; 3]);

    impl fmt::Display for Perm3 {
        fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
            write!(f, "{:?}", self.0)
        }
    }

    impl GroupElement for Perm3 {
        fn identity() -> Self {
            Perm3([0, 1, 2])
        }

        fn inverse(&self) -> Self {
            let mut inv = [0; 3];
            for (i, &j) in self.0.iter().enumerate() {
                inv[j] = i;
            }
            Perm3(inv)
        }

        fn op(&self, other: &Self) -> Self {
            Perm3([other.0[self.0[0]], other.0[self.0[1]], other.0[self.0[2]]])
        }
    }

    impl ElementLibGAP for Perm3 {}

    #[test]
    fn test_symmetric_group_s3() {
        // GAP: G := Group((1,2,3),(1,2));; SortedList(List(ConjugacyClasses(G), Size))
        // = [1, 2, 3]; Size(Centre(G)) = 1; Exponent(G) = 6.
        let c3 = Perm3([1, 2, 0]);
        let t = Perm3([1, 0, 2]);
        let mut g = GroupLibGAP::new(vec![c3.clone(), t.clone()], Some(6), false);
        assert_eq!(g.compute_elements().map(|e| e.len()), Some(6));
        let mut sizes: Vec<usize> = g.conjugacy_classes().iter().map(|c| c.len()).collect();
        sizes.sort_unstable();
        assert_eq!(sizes, vec![1, 2, 3]);
        assert_eq!(g.center(), vec![Perm3::identity()]);
        assert_eq!(g.exponent(), Some(6));
        assert!(g.contains(&c3.op(&t)));
    }
}
