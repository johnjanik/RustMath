//! Permutation groups - finite groups of permutations
//!
//! This module implements permutation groups including the symmetric
//! and alternating groups.

use rustmath_combinatorics::Permutation;
use rustmath_integers::Integer;
use std::fmt;

/// A permutation group - a subgroup of the symmetric group
#[derive(Clone, Debug)]
pub struct PermutationGroup {
    /// Degree of the group (permutations act on {0, 1, ..., n-1})
    degree: usize,
    /// Generators of the group
    generators: Vec<Permutation>,
}

impl PermutationGroup {
    /// Create a new permutation group from generators
    pub fn new(degree: usize, generators: Vec<Permutation>) -> Result<Self, String> {
        // Validate that all generators have the correct degree
        for gen in &generators {
            if gen.size() != degree {
                return Err(format!(
                    "Generator has degree {}, expected {}",
                    gen.size(),
                    degree
                ));
            }
        }

        Ok(PermutationGroup { degree, generators })
    }

    /// Create the symmetric group S_n as a PermutationGroup
    ///
    /// The symmetric group S_n is the group of all permutations of n elements.
    /// It is generated by adjacent transpositions (i, i+1) for i = 0, ..., n-2.
    ///
    /// # Arguments
    ///
    /// * `n` - The degree of the symmetric group
    ///
    /// # Examples
    ///
    /// ```
    /// use rustmath_groups::PermutationGroup;
    ///
    /// // Create S_4 (symmetric group on 4 elements)
    /// let s4 = PermutationGroup::symmetric(4);
    /// assert_eq!(s4.degree(), 4);
    /// ```
    pub fn symmetric(n: usize) -> Self {
        // Generate S_n using adjacent transpositions
        let mut generators = Vec::new();

        if n >= 2 {
            for i in 0..n - 1 {
                let mut perm = Vec::new();
                for j in 0..n {
                    if j == i {
                        perm.push(i + 1);
                    } else if j == i + 1 {
                        perm.push(i);
                    } else {
                        perm.push(j);
                    }
                }
                if let Some(p) = Permutation::from_vec(perm) {
                    generators.push(p);
                }
            }
        }

        PermutationGroup::new(n, generators).unwrap()
    }

    /// Create the cyclic group C_n as a PermutationGroup
    ///
    /// The cyclic group C_n is the group of rotations of n elements.
    /// It is generated by a single cyclic permutation (0 1 2 ... n-1).
    ///
    /// # Arguments
    ///
    /// * `n` - The order of the cyclic group
    ///
    /// # Examples
    ///
    /// ```
    /// use rustmath_groups::PermutationGroup;
    ///
    /// // Create C_5 (cyclic group of order 5)
    /// let c5 = PermutationGroup::cyclic(5);
    /// assert_eq!(c5.degree(), 5);
    /// ```
    pub fn cyclic(n: usize) -> Self {
        let mut generators = Vec::new();

        if n >= 2 {
            // Create the cyclic permutation (0 1 2 ... n-1) -> (1 2 3 ... n-1 0)
            let mut perm: Vec<usize> = (1..n).collect();
            perm.push(0);

            if let Some(p) = Permutation::from_vec(perm) {
                generators.push(p);
            }
        } else if n == 1 {
            // C_1 is trivial, use identity
            if let Some(p) = Permutation::from_vec(vec![0]) {
                generators.push(p);
            }
        }

        PermutationGroup::new(n, generators).unwrap()
    }

    /// Create the dihedral group of order 2n as a permutation group.
    ///
    /// Follows the GAP `DihedralGroup(IsPermGroup, 2n)` / Sage `DihedralGroup(n)`
    /// convention:
    /// - for n ≥ 3, the symmetry group of the regular n-gon on n points,
    ///   generated by the rotation (0 1 … n−1) and the reflection i ↦ n−1−i;
    /// - D_1 = ⟨(0 1)⟩ on 2 points (order 2);
    /// - D_2 = ⟨(0 1), (2 3)⟩ on 4 points (the Klein four-group).
    ///
    /// # Panics
    ///
    /// If `n == 0`.
    ///
    /// # Examples
    ///
    /// ```
    /// use rustmath_groups::PermutationGroup;
    /// use rustmath_integers::Integer;
    ///
    /// let d5 = PermutationGroup::dihedral(5);
    /// assert_eq!(d5.degree(), 5);
    /// assert_eq!(d5.order(), Integer::from(10));
    /// ```
    pub fn dihedral(n: usize) -> Self {
        assert!(n >= 1, "Dihedral group D_n requires n >= 1");
        let perm = |images: Vec<usize>| {
            Permutation::from_vec(images).expect("dihedral generator is a permutation")
        };
        match n {
            1 => PermutationGroup::new(2, vec![perm(vec![1, 0])]).unwrap(),
            2 => PermutationGroup::new(4, vec![perm(vec![1, 0, 2, 3]), perm(vec![0, 1, 3, 2])])
                .unwrap(),
            _ => {
                let rotation = perm((0..n).map(|i| (i + 1) % n).collect());
                let reflection = perm((0..n).map(|i| n - 1 - i).collect());
                PermutationGroup::new(n, vec![rotation, reflection]).unwrap()
            }
        }
    }

    /// Get the degree of the group
    pub fn degree(&self) -> usize {
        self.degree
    }

    /// Get the generators
    pub fn generators(&self) -> &[Permutation] {
        &self.generators
    }

    /// The order |G| of the group generated by [`generators`](Self::generators),
    /// computed exactly by deterministic Schreier–Sims
    /// ([`crate::bsgs::group_order`]).
    ///
    /// # Examples
    ///
    /// ```
    /// use rustmath_groups::PermutationGroup;
    /// use rustmath_integers::Integer;
    ///
    /// assert_eq!(PermutationGroup::symmetric(5).order(), Integer::from(120));
    /// assert_eq!(PermutationGroup::cyclic(7).order(), Integer::from(7));
    /// ```
    pub fn order(&self) -> Integer {
        let gens: Vec<Vec<usize>> =
            self.generators.iter().map(|g| g.as_slice().to_vec()).collect();
        crate::bsgs::group_order(&gens, self.degree)
            .expect("generators were validated as permutations of the group degree")
    }
}

impl fmt::Display for PermutationGroup {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "PermutationGroup(degree={}, generators={})",
            self.degree,
            self.generators.len()
        )
    }
}

/// The symmetric group S_n
pub struct SymmetricGroup {
    n: usize,
    group: PermutationGroup,
}

impl SymmetricGroup {
    /// Create the symmetric group S_n
    pub fn new(n: usize) -> Self {
        // Generate S_n using adjacent transpositions
        let mut generators = Vec::new();

        if n >= 2 {
            for i in 0..n - 1 {
                let mut perm = Vec::new();
                for j in 0..n {
                    if j == i {
                        perm.push(i + 1);
                    } else if j == i + 1 {
                        perm.push(i);
                    } else {
                        perm.push(j);
                    }
                }
                if let Some(p) = Permutation::from_vec(perm) {
                    generators.push(p);
                }
            }
        }

        let group = PermutationGroup::new(n, generators).unwrap();

        SymmetricGroup { n, group }
    }

    /// Get the degree n
    pub fn degree(&self) -> usize {
        self.n
    }

    /// Get the order of S_n (= n!)
    pub fn order(&self) -> usize {
        factorial(self.n)
    }

    /// Get the underlying permutation group
    pub fn group(&self) -> &PermutationGroup {
        &self.group
    }
}

/// The alternating group A_n (even permutations)
pub struct AlternatingGroup {
    n: usize,
    group: PermutationGroup,
}

impl AlternatingGroup {
    /// Create the alternating group A_n
    pub fn new(n: usize) -> Self {
        if n < 3 {
            // A_1 and A_2 are trivial
            let identity = Permutation::identity(n);
            let group = PermutationGroup::new(n, vec![identity]).unwrap();
            return AlternatingGroup { n, group };
        }

        // Generate A_n using 3-cycles
        let mut generators = Vec::new();

        // Add the 3-cycle (0, 1, 2) -> (1, 2, 0)
        if n >= 3 {
            let mut perm = vec![1, 2, 0];
            perm.extend(3..n);
            if let Some(p) = Permutation::from_vec(perm) {
                generators.push(p);
            }
        }

        // Add more 3-cycles for higher degrees
        if n >= 4 {
            for i in 3..n {
                let mut perm: Vec<usize> = (0..n).collect();
                // Create 3-cycle (0, 1, i)
                perm[0] = 1;
                perm[1] = i;
                perm[i] = 0;
                if let Some(p) = Permutation::from_vec(perm) {
                    generators.push(p);
                }
            }
        }

        let group = PermutationGroup::new(n, generators).unwrap();

        AlternatingGroup { n, group }
    }

    /// Get the degree n
    pub fn degree(&self) -> usize {
        self.n
    }

    /// Get the order of A_n (= n!/2)
    pub fn order(&self) -> usize {
        if self.n < 2 {
            1
        } else {
            factorial(self.n) / 2
        }
    }

    /// Get the underlying permutation group
    pub fn group(&self) -> &PermutationGroup {
        &self.group
    }
}

/// Compute factorial
fn factorial(n: usize) -> usize {
    (1..=n).product()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_permutation_group_creation() {
        // Create Z/2Z as a permutation group
        let swap = Permutation::from_vec(vec![1, 0]).unwrap();
        let group = PermutationGroup::new(2, vec![swap]);
        assert!(group.is_ok());
    }

    #[test]
    fn test_permutation_group_degree() {
        let swap = Permutation::from_vec(vec![1, 0]).unwrap();
        let group = PermutationGroup::new(2, vec![swap]).unwrap();
        assert_eq!(group.degree(), 2);
    }

    #[test]
    fn test_symmetric_group_s3() {
        let s3 = SymmetricGroup::new(3);
        assert_eq!(s3.degree(), 3);
        assert_eq!(s3.order(), 6); // 3! = 6
    }

    #[test]
    fn test_symmetric_group_s4() {
        let s4 = SymmetricGroup::new(4);
        assert_eq!(s4.degree(), 4);
        assert_eq!(s4.order(), 24); // 4! = 24
    }

    #[test]
    fn test_alternating_group_a3() {
        let a3 = AlternatingGroup::new(3);
        assert_eq!(a3.degree(), 3);
        assert_eq!(a3.order(), 3); // 3!/2 = 3
    }

    #[test]
    fn test_alternating_group_a4() {
        let a4 = AlternatingGroup::new(4);
        assert_eq!(a4.degree(), 4);
        assert_eq!(a4.order(), 12); // 4!/2 = 12
    }

    #[test]
    fn test_alternating_group_a5() {
        let a5 = AlternatingGroup::new(5);
        assert_eq!(a5.degree(), 5);
        assert_eq!(a5.order(), 60); // 5!/2 = 60
    }

    #[test]
    fn test_factorial() {
        assert_eq!(factorial(0), 1);
        assert_eq!(factorial(1), 1);
        assert_eq!(factorial(2), 2);
        assert_eq!(factorial(3), 6);
        assert_eq!(factorial(4), 24);
        assert_eq!(factorial(5), 120);
    }

    #[test]
    fn test_group_generators() {
        let swap = Permutation::from_vec(vec![1, 0]).unwrap();
        let group = PermutationGroup::new(2, vec![swap.clone()]).unwrap();

        let gens = group.generators();
        assert_eq!(gens.len(), 1);
    }

    #[test]
    fn test_s2_generators() {
        let s2 = SymmetricGroup::new(2);
        // S_2 generated by one transposition
        assert_eq!(s2.group().generators().len(), 1);
    }

    #[test]
    fn test_s3_generators() {
        let s3 = SymmetricGroup::new(3);
        // S_3 generated by two adjacent transpositions
        assert_eq!(s3.group().generators().len(), 2);
    }

    #[test]
    fn test_generated_orders_match_formulas() {
        // Schreier–Sims orders of the generating sets agree with n! and n!/2.
        for n in 1..=7 {
            let s = SymmetricGroup::new(n);
            assert_eq!(s.group().order(), Integer::from(s.order() as u64));
            if n >= 3 {
                let a = AlternatingGroup::new(n);
                assert_eq!(a.group().order(), Integer::from(a.order() as u64));
            }
        }
    }

    #[test]
    fn test_dihedral_orders() {
        // |D_n| = 2n; degrees follow GAP DihedralGroup(IsPermGroup, 2n):
        // D_1 on 2 points, D_2 on 4 points, D_n on n points for n >= 3.
        let expected_degree = [2, 4, 3, 4, 5, 6, 7, 8];
        for n in 1..=8usize {
            let d = PermutationGroup::dihedral(n);
            assert_eq!(d.degree(), expected_degree[n - 1], "degree of D_{}", n);
            assert_eq!(d.order(), Integer::from(2 * n as u64), "order of D_{}", n);
        }
    }

    #[test]
    fn test_dihedral_relations() {
        // r^n = s^2 = 1 and s r s = r^{-1} for the n-gon generators.
        let n = 6;
        let d = PermutationGroup::dihedral(n);
        let (r, s) = (&d.generators()[0], &d.generators()[1]);
        assert_eq!(r.order(), n);
        assert_eq!(s.order(), 2);
        let srs = s.compose(&r.compose(s).unwrap()).unwrap();
        assert_eq!(srs, r.inverse());
    }

    #[test]
    #[should_panic(expected = "Dihedral group D_n requires n >= 1")]
    fn test_dihedral_zero_panics() {
        PermutationGroup::dihedral(0);
    }
}
