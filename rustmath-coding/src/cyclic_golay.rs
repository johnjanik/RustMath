//! The two cyclic binary Golay codes of length 23 and their Steiner systems S(4,7,23).
//!
//! MAGMA: ch. 152 `CyclicCode(n, g)` (worked example H152E5: the length 23 binary Golay code as a
//! cyclic code from a degree 11 factor of `x^23 - 1`), `QRCode`; ch. 147 for the designs.
//! Digests: `rustmath-lava/docs/Chapter_152_Linear_Codes_over_Finite_Fields.md`,
//! `Chapter_147_Incidence_Structures_and_Designs.md`.
//!
//! Mathematics:
//! - F. J. MacWilliams, N. J. A. Sloane, *The Theory of Error-Correcting Codes*, North-Holland
//!   1977, ch. 16 (quadratic residue codes; the binary Golay code as the QR code of length 23).
//! - E. Witt, *Ueber Steinersche Systeme*, Abh. Math. Sem. Hamburg 12 (1938) 265-275 (the
//!   S(4,7,23) is unique up to isomorphism, with automorphism group M23).
//! - The paper `golay_m23.tex` of the owner's M23 repository (`d05475b`), Section 2 (the two
//!   cyclic codes, Lemma `lem:twocodes`: a 23-cycle preserves exactly two Steiner systems
//!   S(4,7,23); for the shift they are the two systems below), and its `m23golay/golay.py`
//!   (`G_PLUS`, `G_MINUS`, `codewords`, `heptads`), ported here.
//!
//! Over `F_2`, `z^23 - 1 = (z - 1) g+(z) g-(z)` with
//! `g+ = z^11 + z^9 + z^7 + z^6 + z^5 + z + 1` (mask `0xAE3`) and
//! `g- = z^11 + z^10 + z^6 + z^5 + z^4 + z^2 + 1` (mask `0xC75`), the reciprocal of `g+`. The
//! cyclic code generated by `g` has the 4096 words `m(z) g(z)`, `deg m < 12`; each is a perfect
//! `[23, 12, 7]` code. Its 253 words of weight 7 (the heptads) form a Steiner system S(4,7,23)
//! on `Z/23`, invariant under the shift `i -> i + 1` and under `i -> 2i`. The map `i -> -i`
//! exchanges the two systems.
//!
//! Words are 23-bit masks: bit `i` is coordinate `i`, the coefficient of `z^i`.
//! [`crate::BinaryGolayCode`] generates exactly `G-` in these coordinates (test
//! `binary_golay_code_is_g_minus`).

use std::sync::OnceLock;

/// The code length 23.
pub const LENGTH: usize = 23;

const FULL: u32 = (1 << LENGTH) - 1;

/// Which of the two cyclic Golay codes: `Plus` is generated by `g+` (`0xAE3`), `Minus` by `g-`
/// (`0xC75`). The sign convention is that of `golay.py` (`+1`, `-1`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum GolaySign {
    /// The code generated by `g+ = z^11 + z^9 + z^7 + z^6 + z^5 + z + 1`.
    Plus,
    /// The code generated by `g- = z^11 + z^10 + z^6 + z^5 + z^4 + z^2 + 1`.
    Minus,
}

impl GolaySign {
    /// Both signs, `Plus` first.
    pub const ALL: [GolaySign; 2] = [GolaySign::Plus, GolaySign::Minus];

    /// The generator polynomial as a mask (bit `i` is the coefficient of `z^i`).
    pub fn generator_polynomial(self) -> u32 {
        match self {
            GolaySign::Plus => 0xAE3,
            GolaySign::Minus => 0xC75,
        }
    }

    /// The other sign (the image of the system under `i -> -i`).
    pub fn opposite(self) -> GolaySign {
        match self {
            GolaySign::Plus => GolaySign::Minus,
            GolaySign::Minus => GolaySign::Plus,
        }
    }

    /// `+1` or `-1`, as in `golay.py`.
    pub fn to_i8(self) -> i8 {
        match self {
            GolaySign::Plus => 1,
            GolaySign::Minus => -1,
        }
    }

    /// The sign of `+1` or `-1`; `None` otherwise.
    pub fn from_i8(s: i8) -> Option<GolaySign> {
        match s {
            1 => Some(GolaySign::Plus),
            -1 => Some(GolaySign::Minus),
            _ => None,
        }
    }

    fn index(self) -> usize {
        match self {
            GolaySign::Plus => 0,
            GolaySign::Minus => 1,
        }
    }
}

impl std::fmt::Display for GolaySign {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(match self {
            GolaySign::Plus => "+",
            GolaySign::Minus => "-",
        })
    }
}

/// The 4096 words `m(z) g(z)`, `deg m < 12`, in the order of the messages `m = 0..4096` (bit `i`
/// of `m` is the coefficient of `z^i`), as in `golay.py` `codewords`.
pub fn codewords(sign: GolaySign) -> Vec<u32> {
    let g = sign.generator_polynomial();
    (0u32..1 << 12)
        .map(|m| {
            (0..12)
                .filter(|i| (m >> i) & 1 == 1)
                .fold(0u32, |w, i| w ^ (g << i))
        })
        .collect()
}

/// The number of words of each weight `0..=23`.
pub fn weight_distribution(sign: GolaySign) -> [u64; 24] {
    let mut out = [0u64; 24];
    for w in codewords(sign) {
        out[w.count_ones() as usize] += 1;
    }
    out
}

struct Tables {
    heptads: Vec<u32>,
    representatives: Vec<u32>,
}

fn tables(sign: GolaySign) -> &'static Tables {
    static CELLS: [OnceLock<Tables>; 2] = [OnceLock::new(), OnceLock::new()];
    CELLS[sign.index()].get_or_init(|| {
        let mut heptads: Vec<u32> = codewords(sign)
            .into_iter()
            .filter(|w| w.count_ones() == 7)
            .collect();
        heptads.sort_unstable();
        let mut representatives: Vec<u32> = heptads
            .iter()
            .map(|&h| {
                (0..LENGTH as u32)
                    .map(|k| rotate(h, k))
                    .min()
                    .expect("23 shifts")
            })
            .collect();
        representatives.sort_unstable();
        representatives.dedup();
        Tables {
            heptads,
            representatives,
        }
    })
}

/// The 253 words of weight 7 (heptads), sorted as integers, computed once.
pub fn heptads(sign: GolaySign) -> &'static [u32] {
    &tables(sign).heptads
}

/// The least mask of each shift orbit of heptads, sorted (11 masks: every orbit has length 23,
/// since 23 is prime and no proper non-empty subset of `Z/23` is shift-invariant).
pub fn heptad_orbit_representatives(sign: GolaySign) -> &'static [u32] {
    &tables(sign).representatives
}

/// The image of `mask` under `i -> i + k` (mod 23).
pub fn rotate(mask: u32, k: u32) -> u32 {
    let k = k % LENGTH as u32;
    let m = mask & FULL;
    if k == 0 {
        return m;
    }
    ((m << k) | (m >> (LENGTH as u32 - k))) & FULL
}

/// The image of `mask` under `i -> -i` (mod 23).
pub fn negate(mask: u32) -> u32 {
    (0..LENGTH)
        .filter(|&i| (mask >> i) & 1 == 1)
        .fold(0u32, |acc, i| acc | 1 << ((LENGTH - i) % LENGTH))
}

/// The image of `mask` under `i -> a i` (mod 23).
pub fn scale(mask: u32, a: u32) -> u32 {
    (0..LENGTH)
        .filter(|&i| (mask >> i) & 1 == 1)
        .fold(0u32, |acc, i| {
            acc | 1 << ((i as u64 * a as u64) % LENGTH as u64)
        })
}

/// The coordinates of `mask`, increasing.
pub fn support(mask: u32) -> Vec<usize> {
    (0..LENGTH).filter(|&i| (mask >> i) & 1 == 1).collect()
}

/// The mask of a set of coordinates in `0..23`. Panics on a coordinate `>= 23`.
pub fn mask_of(points: &[usize]) -> u32 {
    points.iter().fold(0u32, |acc, &i| {
        assert!(i < LENGTH, "mask_of: coordinate {i} is not in 0..23");
        acc | 1 << i
    })
}
